#!/usr/bin/env python3
"""Graphics and palette data for the VBXE build.

The tiles come from the Amiga AGA port's sheets (assets/tiles/aga): one sheet
per layer (fore/back) and per palette bank (0/1), 256 8x8 tiles each. The
two banks draw the same tiles with different colours, so each pixel is
stored as the index of its (bank 0 colour, bank 1 colour) pair: switching
the arcade palette is then just loading the other VBXE palette.

  fg pairs: VBXE colours 1..127 (0 = transparent, black in both banks)
  bg pairs: VBXE colours 128..255

Writes gen/fgtiles.bin, gen/bgtiles.bin (256 x 64 bytes) and gen/data.asm
(the two palettes and the table of fully transparent fg tiles).
"""
import sys
from pathlib import Path
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import render  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
GEN = ROOT / "gen"


def asm_bytes(name, data, per=16):
    out = [f"{name}"]
    for i in range(0, len(data), per):
        out.append("        dta " + ",".join(f"${b:02X}" for b in data[i:i + per]))
    return out


def main():
    sheets = render.load_sheets()
    pal = np.zeros((2, 256, 3), np.uint8)
    out = {}
    blank = []
    for layer, base, limit in (("fore", 1, 128), ("back", 128, 256)):
        s0 = sheets[layer, 0]
        s1 = sheets[layer, 1]
        pairs = {}
        if layer == "fore":
            pairs[((0, 0, 0), (0, 0, 0))] = 0
        tiles = bytearray()
        for code in range(256):
            x, y = (code & 31) * 8, (code >> 5) * 8
            for dy in range(8):
                for dx in range(8):
                    key = (tuple(int(v) for v in s0[y + dy, x + dx]), tuple(int(v) for v in s1[y + dy, x + dx]))
                    if key not in pairs:
                        pairs[key] = base + len([k for k, v in pairs.items() if v >= base])
                        assert pairs[key] < limit, f"too many {layer} colours"
                    tiles.append(pairs[key])
            if layer == "fore":
                blank.append(1 if not any(tiles[-64:]) else 0)
        for (c0, c1), idx in pairs.items():
            pal[0, idx] = c0
            pal[1, idx] = c1
        out[layer] = tiles
        print(f"{layer}: {len(pairs)} colour pairs")
    (GEN / "fgtiles.bin").write_bytes(out["fore"])
    (GEN / "bgtiles.bin").write_bytes(out["back"])
    lines = ["; generated by tools/make_data.py -- do not edit"]
    for b in range(2):
        for c, name in enumerate("rgb"):
            lines += asm_bytes(f"pal{b}_{name}", pal[b, :, c].tolist())
    lines += asm_bytes("fg_blank", blank)
    (GEN / "data.asm").write_text("\n".join(lines) + "\n")
    print("blank fg tiles:", sum(blank))


if __name__ == "__main__":
    main()
