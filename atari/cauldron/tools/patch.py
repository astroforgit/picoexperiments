#!/usr/bin/env python3
"""Patches of the C64 program for the Atari runtime: patch.py ENTRY.bin

Reads the code map (gen/codemap.json, tools/codemap.py) and writes
  gen/patchlist.json  [address, [bytes]] (bytes may be '<label'/'>label')
  gen/hooks.asm       trampolines and the table of screen writer sites

Every instruction with an absolute operand in the C64 chips is changed:
  VIC-II $D000-$D03F -> shadow $DE00 (same low byte), SID $D400 -> $DF00;
  reads of the raster ($D011/$D012), the collision latches ($D01E/$D01F),
  the SID oscillator 3 / envelope 3 (random numbers) and the joystick port
  ($DC00), and stores to $D019, become JSRs to stubs.
Stores into screen RAM ($4000-$43E7) and colour RAM ($D800-$DBE7) become
JSRs to trampolines that mark the store site (its rows are dirty); indirect
stores mark the exact row, or the character when the target is a charset
($7000-$7FFF). The coarse scroll calls are hooked so the renderer can shift
the scrolled band instead of redrawing it.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from dis6502 import OPS, MODES, fmt  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GEN = os.path.join(ROOT, 'gen')

READ_STUBS = {0xD011: 'rd_d011', 0xD012: 'rd_d012', 0xD01E: 'rd_d01e', 0xD01F: 'rd_d01f',
              0xD41B: 'rd_rand', 0xD41C: 'rd_rand', 0xDC00: 'rd_joy'}
VECTORS = {0xFFFA: 'c64_nmi', 0xFFFB: 'c64_nmi+1', 0xFFFE: 'c64_irq', 0xFFFF: 'c64_irq+1'}
# the coarse scroll routines' own stores (their effect is applied as a shift)
SCROLL_STORES = [(0xA6AE, 0xA6E4), (0xA788, 0xA7FC), (0xA85A, 0xA890), (0xA930, 0xA9A4)]
SCROLL_CALLS = {0xA69C: ('hk_left', 0xA6A3), 0x9A20: ('hk_left', 0xA6A3), 0xA848: ('hk_right', 0xA84F)}
# indirect stores that never reach the screen, colour RAM or a charset
BRANCH = {'bpl', 'bmi', 'bvc', 'bvs', 'bcc', 'bcs', 'bne', 'beq'}


def screen_rows(lo, hi):
    """Rows of screen/colour RAM a store to lo..hi can reach."""
    rows = set()
    for base in (0x4000, 0xD800):
        a, b = max(lo, base), min(hi, base + 999)
        if a <= b:
            rows |= set(range((a - base) // 40, (b - base) // 40 + 1))
    return sorted(rows)


def main():
    ram = open(sys.argv[1], 'rb').read() if len(sys.argv) > 1 else open(os.path.join(GEN, 'entry.bin'), 'rb').read()
    code = {int(k, 16): v for k, v in json.load(open(os.path.join(GEN, 'codemap.json')))['code'].items()}
    targets = set()
    for pc in code:
        n, m = OPS[ram[pc]]
        s, ln, t = fmt(ram, pc, lambda a: ram[a])
        if m == 'rel' or n in ('jsr', 'jmp'):
            targets.add(t)

    patches = []
    asm = ['; generated by tools/patch.py: screen writer trampolines']
    sites = []          # (label, rows)
    nind = 0

    def text(pc):
        return fmt(ram, pc, lambda a: ram[a & 0xFFFF])[0]

    for pc in sorted(code):
        op = ram[pc]
        n, m = OPS[op]
        ln = 1 + MODES[m]
        w = ram[pc + 1] | ram[pc + 2] << 8 if ln == 3 else None
        if pc in SCROLL_CALLS:
            lab, tgt = SCROLL_CALLS[pc]
            assert n == 'jsr' and w == tgt, f'{pc:04x}'
            patches.append((pc, [0x20, '<' + lab, '>' + lab]))
            continue
        if ln == 3 and m != 'ind' and n not in ('jsr', 'jmp'):
            if w in VECTORS:
                assert n == 'sta'
                v = VECTORS[w]
                patches.append((pc + 1, ['<' + v, '>' + v]))
                continue
            if w in READ_STUBS and n not in ('sta', 'stx', 'sty') and not (w == 0xD011 and n in ('ora', 'and')):
                if n != 'lda' or m != 'abs':
                    sys.exit(f'{pc:04x}: {text(pc)} needs a stub')
                lab = READ_STUBS[w]
                patches.append((pc, [0x20, '<' + lab, '>' + lab]))
                continue
            if w == 0xD019 and n == 'sta':
                assert m == 'abs'
                patches.append((pc, [0x20, '<wr_d019', '>wr_d019']))
                continue
            if 0xD000 <= w < 0xD040:
                patches.append((pc + 2, [0xDE]))
                continue
            if 0xD400 <= w < 0xD420:
                patches.append((pc + 2, [0xDF]))
                continue
            if 0xD040 <= w < 0xD800 and not (w == 0xD7FF and m == 'abx'):
                sys.exit(f'{pc:04x}: {text(pc)} touches ${w:04X}')
            if 0xDC00 <= w < 0xDE00 and n in ('lda', 'ldx', 'ldy', 'cmp', 'bit', 'and', 'ora', 'eor', 'adc', 'sbc'):
                if w not in (0xDC0E,):
                    sys.exit(f'{pc:04x}: {text(pc)} reads a CIA register')
            if n in ('sta', 'stx', 'sty', 'inc', 'dec', 'asl', 'lsr', 'rol', 'ror'):
                reach = (w, w + (255 if m in ('abx', 'aby') else 0))
                rows = screen_rows(*reach)
                if w == 0xD7FF:
                    rows = screen_rows(0xD800, 0xD8FE)
                if rows:
                    i = len(sites)
                    lab = f'hs_{i}'
                    sites.append((lab, rows))
                    asm += [f'{lab}  {text(pc)}', '        php', f'        dec site_hit+{i}', '        plp', '        rts']
                    patches.append((pc, [0x20, '<' + lab, '>' + lab]))
            continue
        if n == 'sta' and m in ('izy', 'izx'):
            if any(a <= pc < b for a, b in SCROLL_STORES):
                continue
            assert m == 'izy', f'{pc:04x}'
            zp = ram[pc + 1]
            span = [pc]
            p = pc + 2
            tail = []
            while p - pc < 3:
                s2, l2, t2 = fmt(ram, p, lambda a: ram[a])
                n2 = OPS[ram[p]][0]
                assert n2 not in BRANCH and n2 not in ('jsr', 'jmp'), f'{pc:04x}: {s2} after the store'
                tail.append((n2, s2))
                p += l2
            inner = [t for t in targets if pc < t < p]
            assert not inner, f'{pc:04x}: branch target inside the patch'
            lab = f'hi_{nind}'
            nind += 1

            def tail_code():
                out = []
                for n2, s2 in tail:
                    if n2 == 'rts':
                        out += ['        pla', '        pla']   # return to the game routine's caller
                    out.append('        ' + s2)
                if tail[-1][0] != 'rts':
                    out.append('        rts')
                return out
            # an unchanged value marks nothing (the game redraws glyphs as they are)
            asm += [f'{lab}  php', f'        cmp (${zp:02x}),y', f'        bne {lab}m', '        plp']
            asm += tail_code()
            asm += [f'{lab}m sta (${zp:02x}),y', '        pha', '        txa', '        pha',
                    '        tya', '        clc', f'        adc ${zp:02x}', '        tax',
                    f'        lda ${(zp + 1) & 0xFF:02x}', '        adc #0', '        jsr mark_addr',
                    '        pla', '        tax', '        pla', '        plp']
            asm += tail_code()
            patches.append((pc, [0x20, '<' + lab, '>' + lab] + [0xEA] * (p - pc - 3)))

    asm.append(f'NSITE = {len(sites)}')
    asm.append('site_r0 dta ' + ','.join(str(r[0]) for _, r in sites))
    asm.append('site_r1 dta ' + ','.join(str(r[-1]) for _, r in sites))
    open(os.path.join(GEN, 'hooks.asm'), 'w').write('\n'.join(asm) + '\n')
    json.dump([[a, b] for a, b in sorted(patches)], open(os.path.join(GEN, 'patchlist.json'), 'w'))
    print(f'{len(patches)} patches, {len(sites)} screen writer sites, {nind} indirect stores')


if __name__ == '__main__':
    main()
