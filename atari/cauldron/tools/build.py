#!/usr/bin/env python3
"""Build cauldron.xex (Cauldron, Atari XL/XE + VBXE).

Inputs: disk/*.prg (tools/d64.py) and gen/codemap.json (tools/codemap.py,
kept in the repository). Steps: the C64 RAM image at the game's entry
point (tools/cauldron.py) -> patches and hooks (tools/patch.py) -> runtime
assembly -> RAM image, code A and bank R into a VRAM payload -> XEX.
"""
import hashlib
import json
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from dis6502 import OPS, MODES  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GEN = os.path.join(ROOT, 'gen')
SRC = os.path.join(ROOT, 'src')
MADS = os.environ.get('MADS', 'mads')
OUT = os.path.join(ROOT, os.environ.get('CAULDRON_OUT', 'cauldron.xex'))

V_STAGE, V_RTIMG = 0x00000, 0x60000
BANKS = [('RBANK_START', 0x7C000), ('NBANK_START', 0x7A000), ('IBANK_START', 0x78000)]
STAGE = 0x8000


def run(*cmd):
    r = subprocess.run([str(c) for c in cmd], cwd=ROOT, capture_output=True, text=True)
    if r.returncode:
        sys.exit(f'{" ".join(map(str, cmd))} failed:\n{r.stdout}{r.stderr}')
    return r.stdout


def assemble(src, *opts):
    """MADS, turning out-of-range short branches into long ones (jeq...)."""
    for _ in range(60):
        r = subprocess.run([MADS, src, *opts], cwd=SRC, capture_output=True, text=True)
        hits = re.findall(r'^(\S+\.asm) \((\d+)\) ERROR: Branch out of range', r.stdout, re.M)
        if not hits:
            if r.returncode or 'ERROR' in r.stdout:
                sys.exit(f'mads {src} failed:\n{r.stdout}{r.stderr}')
            return r.stdout
        for name, line in set(hits):
            path = os.path.join(SRC, name)
            lines = open(path).read().split('\n')
            i = int(line) - 1
            lines[i] = re.sub(r'\b(beq|bne|bcc|bcs|bmi|bpl|bvc|bvs)\b', lambda m: 'j' + m.group(1)[1:],
                              lines[i], count=1)
            open(path, 'w').write('\n'.join(lines))
    sys.exit('mads: branches did not settle')


def labels(path):
    out = {}
    for line in open(path).read().splitlines():
        p = line.split()
        if len(p) == 3:
            try:
                out[p[2].upper()] = int(p[1], 16)
            except ValueError:
                pass
    return out


def xex_segments(data):
    p, segs = 0, []
    while p < len(data):
        s = int.from_bytes(data[p:p + 2], 'little'); p += 2
        if s == 0xFFFF:
            continue
        e = int.from_bytes(data[p:p + 2], 'little'); p += 2
        segs.append((s, data[p:p + e - s + 1])); p += e - s + 1
    return segs


def seg(start, data):
    return start.to_bytes(2, 'little') + (start + len(data) - 1).to_bytes(2, 'little') + bytes(data)


def evaluate(expr, lab):
    v = 0
    for term in expr.split('+'):
        term = term.strip()
        if term.startswith('$'):
            v += int(term[1:], 16)
        elif term.isdigit():
            v += int(term)
        else:
            v += lab[term.upper()]
    return v


def resolve(patch_bytes, lab):
    out = []
    for b in patch_bytes:
        if isinstance(b, int):
            out.append(b)
        elif b.startswith('<'):
            out.append(evaluate(b[1:], lab) & 0xFF)
        elif b.startswith('>'):
            out.append(evaluate(b[1:], lab) >> 8 & 0xFF)
        else:
            raise ValueError(b)
    return out


def vbx_operands(lst_path):
    """(address of the high byte, MEMAC-A bank or 0) of absolute VBXE register operands."""
    out = []
    pat = re.compile(r'^\s*\d+\s+([0-9A-F]{4})\s+((?:[0-9A-F]{2} ?)+)')
    bank = 0
    for line in open(lst_path, errors='replace').read().splitlines():
        for name, v in BANKS:
            if re.search(r'\b' + name + r'\b', line, re.I):
                bank = 0x80 | v >> 12
        m = pat.match(line)
        if not m:
            continue
        addr = int(m.group(1), 16)
        b = [int(x, 16) for x in m.group(2).split()]
        if len(b) == 3 and b[0] in OPS and MODES[OPS[b[0]][1]] == 2 and b[2] == 0xD6 and 0x40 <= b[1] < 0x60:
            out.append((addr + 2, bank if addr >= 0xE000 else 0))
    return sorted(set(out))


def sound_tables():
    k8 = 63337 / (2 * 985248 / 16777216)
    rcp = [round(k8 / (m + 0.5)) for m in range(128, 256)]
    att = [2, 8, 16, 24, 38, 56, 68, 80, 100, 250, 500, 800, 1000, 3000, 5000, 8000]
    ainc = [min(0xFFFF, round(255 * 20 * 256 / t)) for t in att]
    dinc = [min(0xFFFF, round(255 * 20 * 256 / (3 * t))) for t in att]
    lines = ['; generated by tools/build.py']
    for name, vals in (('rcp', rcp), ('ainc', ainc), ('dinc', dinc)):
        for part, f in (('lo', lambda v: v & 255), ('hi', lambda v: v >> 8)):
            lines.append(f'{name}_{part}')
            for i in range(0, len(vals), 16):
                lines.append('        dta ' + ','.join(f'${f(v):02X}' for v in vals[i:i + 16]))
    return '\n'.join(lines) + '\n'


def vline_tables():
    """VCOUNT -> C64 raster line / 2. The vertical blank NMI (scanline 248)
    is C64 line 251, where the game's bottom IRQ runs."""
    pal = [((2 * v + 3) % 312) >> 1 for v in range(156)]
    ntsc = []
    for v in range(156):
        d = (2 * v - 248) % 262
        ntsc.append(((251 + d * 312 // 262) % 312) >> 1)
    out = ['; generated by tools/build.py: VCOUNT -> C64 line / 2']
    for name, t in (('vline_pal', pal), ('vline_ntsc', ntsc)):
        out.append(name)
        for i in range(0, 156, 13):
            out.append('        dta ' + ','.join(str(x) for x in t[i:i + 13]))
    return '\n'.join(out) + '\n'


def main():
    sys.path.insert(0, os.path.join(ROOT, 'tools'))
    import cauldron
    if not os.path.exists(os.path.join(GEN, 'codemap.json')):
        sys.exit('gen/codemap.json missing: run tools/codemap.py')
    c = cauldron.Cauldron()
    entry = bytearray(c.mem.ram)
    open(os.path.join(GEN, 'entry.bin'), 'wb').write(bytes(entry))
    print(run(sys.executable, os.path.join(ROOT, 'tools', 'patch.py')).strip())
    plist = json.load(open(os.path.join(GEN, 'patchlist.json')))
    open(os.path.join(GEN, 'entry.asm'), 'w').write(f'ENTRY_PC = ${c.cpu.pc:04X}\nENTRY_SP = ${c.cpu.sp:02X}\n')
    open(os.path.join(GEN, 'sound-tables.asm'), 'w').write(sound_tables())
    open(os.path.join(GEN, 'vline.asm'), 'w').write(vline_tables())

    out = assemble('runtime.asm', '-o:../gen/runtime.obx', '-l:../gen/runtime.lst', '-t:../gen/runtime.lab')
    print('\n'.join(l.strip() for l in out.splitlines() if ':' in l and ('end' in l or 'vars' in l or 'code' in l)))
    lab = labels(os.path.join(GEN, 'runtime.lab'))
    code_a = bytearray(0x0D00)              # $0200-$0EFF
    banks = []                              # images of $E000-$FFFF: R, N, I
    ram = bytearray(entry)
    ram[0xD800:0xDC00] = bytes(c.colram)
    ram[0xDC00:0xE000] = bytes(0x400)
    for s, d in xex_segments(open(os.path.join(GEN, 'runtime.obx'), 'rb').read()):
        if 0x0200 <= s < 0x0F00:
            assert s + len(d) <= 0x0F00, f'segment ${s:04X}'
            code_a[s - 0x200:s - 0x200 + len(d)] = d
        elif 0xE000 <= s:
            if s == 0xE000:
                banks.append(bytearray(0x2000))
            assert s + len(d) <= 0x10000
            banks[-1][s - 0xE000:s - 0xE000 + len(d)] = d
        elif 0xDC10 <= s < 0xE000:
            ram[s:s + len(d)] = d
        else:
            sys.exit(f'runtime segment at ${s:04X}')
    rel = vbx_operands(os.path.join(GEN, 'runtime.lst'))
    entries = []
    for a, bk in rel:
        if bk:                              # in a code bank: through MEMAC-B
            v = (bk & 0x7F) << 12 | (a - 0xE000)
            entries.append((0x80 | v >> 14, 0x4000 + (v & 0x3FFF)))
        else:
            entries.append((0, a))
    lines = ['; generated by tools/build.py: VBXE register operands (see relocate)', 'reloc']
    lines += [f'        dta ${m:02X},${w & 0xFF:02X},${w >> 8:02X}' for m, w in entries]
    lines.append('        dta 0,0,0')
    open(os.path.join(GEN, 'reloc.asm'), 'w').write('\n'.join(lines) + '\n')
    print(f'VBXE operands: {len(rel)}')

    for a, b in plist:
        b = resolve(b, lab)
        ram[a:a + len(b)] = bytes(b)
    ram[0xDE00:0xDE40] = bytes(c.vic)
    ram[0xDF00:0xDF20] = bytes(c.sid)

    assert len(banks) == len(BANKS), len(banks)
    payload = [(V_STAGE, bytes(ram)), (V_RTIMG + 0x200, bytes(code_a))]
    payload += [(v, bytes(img)) for (_, v), img in zip(BANKS, banks)]
    blob = {}
    for addr, data in payload:
        for i, v in enumerate(data):
            blob[addr + i] = v
    chunks = sorted({a >> 12 for a in blob})
    open(os.path.join(GEN, 'boot-defs.asm'), 'w').write(
        f'RT_BOOT = ${lab["RT_BOOT"]:04X}\nV_RTIMG = ${V_RTIMG:05X}\n')
    assemble('boot.asm', '-o:../gen/boot.obx', '-l:../gen/boot.lst', '-t:../gen/boot.lab')
    blab = labels(os.path.join(GEN, 'boot.lab'))
    x = bytearray(b'\xff\xff')
    for s, d in xex_segments(open(os.path.join(GEN, 'boot.obx'), 'rb').read()):
        x += seg(s, d)
    x += seg(0x2E2, blab['DETECT'].to_bytes(2, 'little'))
    for ch in chunks:
        a = ch << 12
        part = bytes(blob.get(a + i, 0) for i in range(0x1000))
        hdr = bytes([a & 0xFF, (a >> 8) & 0xFF, a >> 16])
        x += seg(STAGE - 3, hdr + part)
        x += seg(0x2E2, blab['UPLOAD'].to_bytes(2, 'little'))
    x += seg(0x2E0, blab['STARTER'].to_bytes(2, 'little'))
    open(OUT, 'wb').write(x)
    name = os.path.basename(OUT)
    open(os.path.join(ROOT, os.path.splitext(name)[0] + '.sha256'), 'w').write(
        hashlib.sha256(x).hexdigest() + f'  {name}\n')
    print(f'{name}: {len(x)} bytes, {len(chunks)} VRAM chunks')


if __name__ == '__main__':
    main()
