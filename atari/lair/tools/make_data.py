def ell_rows(rx, ry, w):
    rowsd = []
    dx = rx
    dy = 0
    while dy <= ry:
        while dx * dx / rx / rx + dy * dy / ry / ry > 1:
            dx -= 1
        k = min(dx, w)
        rowsd.append((dy, dx, k))
        dy += 1
    return rowsd


