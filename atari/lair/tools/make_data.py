#!/usr/bin/env python3
"""Build the data of The Lair VBXE port from the PICO-8 cartridge.

The cart is run in the Lua shim of tools/pico_ref.py, and the tables the
game builds (classes with their inheritance resolved, state handlers,
sprite layouts, hitboxes, palettes, difficulties, stages, waves) are read
from the live Lua state, so they are exactly the cart's values.

Writes:
  data/gfx.bin        8192 bytes   sprite sheet, 4 bpp (staged to VRAM)
  data/vr_*.bin                    VRAM images: font, XDLs, reflection rows,
                                   moons, shadows, outlined font, floor strips,
                                   map rows
  gen/load.asm                     XEX segments that stage the VRAM images
  gen/params.asm                   constants (class, state, bank numbers...)
  gen/tables.asm                   tables at $a000 (classes, sprite layouts,
                                   texts, waves, floor offsets...)
  gen/hi.asm                       tables under the OS ROM (sfx, music, sine,
                                   normalisation, palettes)
"""
