def dta(name, values, width=16):
    lines = [f'{name}']
    for i in range(0, len(values), width):
        lines.append('        dta ' + ','.join(str(v & 255) for v in values[i:i + width]))
    if not values:
        lines.append('        ; (empty)')
    return '\n'.join(lines) + '\n'


def words(name, labels):
    return (f'{name}_lo\n' + ''.join(f'        dta <{x}\n' for x in labels) +
            f'{name}_hi\n' + ''.join(f'        dta >{x}\n' for x in labels))


