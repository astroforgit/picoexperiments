def rget(cls, key):
    v = L.eval(f'rget("{cls}","{key}")')
    return v


def num(v, default=0):
    if v is None or v is False:
        return default
    if v is True:
        return 1
    return v


def b(v):
    return int(v) & 255


def fx88(v):
    """signed 8.8"""
    n = int(round(num(v) * 256))
    return n & 0xffff


def frac(v):
    """fraction byte, 1.0 -> 0 (meaning 'unchanged')"""
    v = num(v)
    if v >= 1:
        return 0
    return max(1, min(255, int(round(v * 256))))


