def circfill(img, stride, cx, cy, r, c):
    # PICO-8 style circle spans (as tools/pico_ref.py)
    x, y = r, 0
    d = 1 - r
    pts = []
    while x >= y:
        pts.append((x, y))
        y += 1
        if d < 0:
            d += 2 * y + 1
        else:
            x -= 1
            d += 2 * (y - x) + 1
    for px, py in pts:
        for (a, bb) in ((px, py), (py, px)):
            for yy in (cy - bb, cy + bb):
                for xx in range(cx - a, cx + a + 1):
                    img[yy * stride + xx] = c


def moon(r):
    size = 2 * (r + 4) + 3
    img = bytearray(size * 128)
    c = r + 5
    circfill(img, 128, c, c, r + 4, stored(0))
    circfill(img, 128, c - 1, c, r, stored(15))
    circfill(img, 128, c + 1, c, r, stored(15))
    circfill(img, 128, c, c - 1, r - 1, stored(7))
    return img, c


