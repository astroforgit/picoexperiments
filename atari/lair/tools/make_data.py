def xdl(base):
    o = bytearray([0x24, 0x08, 23, 0x10, 0xff])   # OVOFF|RPTL, ATT narrow
    for r in range(128):
        addr = base + r * 128
        if r % 2 == 0:
            o += bytes([0x62, 0x20, 1])
        else:
            o += bytes([0x42, 0x20 | (0x80 if r == 127 else 0)])
        o += bytes([addr & 255, (addr >> 8) & 255, addr >> 16, 0, 0])
    return o


for i, base in enumerate((0x00000, 0x04000, 0x08000)):
    x = xdl(base)
    font[0x1000 + i * 0x400:0x1000 + i * 0x400 + len(x)] = x
vr[0x0c000] = bytes(font)

# reflection rows at $1c000: row i shows the cart's four nested spans for
# a half width of i/2 pixels, centred on column 48 (stride 128)
HN = [(1.0, 1), (0.6, 5), (0.35, 13), (0.2, 15)]
