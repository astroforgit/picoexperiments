def cval(c, key, conv=lambda v: b(num(v))):
    return conv(rget(c, key)) if c else 0


def ctab(name, key, conv=lambda v: b(num(v)), clist=None):
    vals = [0] + [cval(c, key, conv) for c in CLASSES]
    return dta(name, vals, 20)


def ctab16(name, key, scale=256):
    vals = [0] + [int(round(num(rget(c, key)) * scale)) & 0xffff for c in CLASSES]
    return dta(name + '_lo', [v & 255 for v in vals], 20) + dta(name + '_hi', [v >> 8 for v in vals], 20)


