def layout_bytes(jy):
    bs = [b(num(jy['jg'] if 'jg' in jy else None)), b(num(jy['jk'] if 'jk' in jy else None))]
    qe = jy['qe']
    qel = [qe[i] for i in range(1, len(qe) + 1)] if qe is not None else []
    bs.append(len(qel))
    for q in qel:
        if q is False or q is None:
            bs += [0, 0, 0, 0, 0]
        else:
            bs += [1, b(q[1]), b(q[2]), b(q[3]), b(q[4])]
    gi = jy['gi']
    gil = [gi[i] for i in range(1, len(gi) + 1)] if gi is not None else []
    bs.append(len(gil))
    for g in gil:
        bs += [b(g[1]), b(g[2]), b(g[3]), b(g[4]), b(g[5])]
    return bs


