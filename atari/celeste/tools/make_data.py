#!/usr/bin/env python3
"""Convert the Celeste PICO-8 cartridge into data for the Atari VBXE port.

Reads ../pico/cart.bin (the raw 32K cartridge memory decoded from
[Platform]/celeste.p8.png by scrip/pico_convert.py) and writes:

  data/gfx.bin      8192 bytes  sprite sheet, 4 bpp, low nibble = left pixel
  data/map.bin      8192 bytes  128x64 tile map (both map halves)
  data/stage.bin              font glyphs, circle masks and both XDLs
  gen/tables.asm              flags, sine/fruit/key tables, sound data
"""
from pathlib import Path
import math
import sys
sys.path.insert(0, str(Path(__file__).resolve().parent))

HERE = Path(__file__).resolve().parent.parent
cart = (HERE / 'pico' / 'cart.bin').read_bytes()
(HERE / 'data').mkdir(exist_ok=True)
(HERE / 'gen').mkdir(exist_ok=True)

# ---------------------------------------------------------------- graphics
(HERE / 'data' / 'gfx.bin').write_bytes(cart[0:0x2000])

tile_map = bytearray(128 * 64)
for y in range(64):
    for x in range(128):
        tile_map[y * 128 + x] = (cart[0x2000 + y * 128 + x] if y < 32
                                 else cart[0x1000 + (y - 32) * 128 + x])
(HERE / 'data' / 'map.bin').write_bytes(tile_map)
flags = cart[0x3000:0x3100]

from make_font import FONT
glyph_order = list(FONT)
stage = bytearray()
for ch in glyph_order:                       # VRAM $25000, 16 bytes/glyph
    rows = FONT[ch].split(',')
    cell = bytearray(16)
    for y, row in enumerate(rows):
        for x, px in enumerate(row):
            if px == '#':
                cell[y * 3 + x] = 0xff
    stage += cell
stage += bytes(0x800 - len(stage))
# Circle masks at VRAM $25800: r=1 (3x3) and r=2 (5x5), stride 8.
circ = bytearray(0x80)
for y, row in enumerate(['.#.', '###', '.#.']):
    for x, px in enumerate(row):
        circ[y * 8 + x] = 0xff if px == '#' else 0
for y, row in enumerate(['.###.', '#####', '#####', '#####', '.###.']):
    for x, px in enumerate(row):
        circ[0x40 + y * 8 + x] = 0xff if px == '#' else 0
stage += circ
stage += bytes(0x800 - len(circ))          # pad to $26000

# XDL: 24 blank lines, then 128 Pico rows in LR/narrow mode. Even rows are
# shown on two TV lines and odd rows on one (1.5x, 192 lines in total).
# Framebuffer row r of the Pico screen sits at bank*$10000 + (64+r)*256 + 64.
def xdl(bank):
    out = bytearray([0x24, 0x08, 23, 0x10, 0xff])   # OVOFF|RPTL, ATT narrow
    for r in range(128):
        addr = bank * 0x10000 + (64 + r) * 256 + 64
        last = r == 127
        if r % 2 == 0:
            out += bytes([0x62, 0x20, 1])           # GMON|RPTL|OVADR, LR
        else:
            out += bytes([0x42, 0x20 | (0x80 if last else 0)])
        out += bytes([addr & 255, (addr >> 8) & 255, addr >> 16, 0, 0])
    return out
x0, x1 = xdl(0), xdl(1)
assert len(x0) <= 0x400
stage += x0 + bytes(0x400 - len(x0)) + x1 + bytes(0x400 - len(x1))
(HERE / 'data' / 'stage.bin').write_bytes(stage)   # VRAM $25000..$26FFF

# ---------------------------------------------------------------- tables
def dta(name, values, width=16):
    lines = [f'{name}']
    for i in range(0, len(values), width):
        lines.append('        dta ' + ','.join(str(v & 255) for v in values[i:i + width]))
    return '\n'.join(lines) + '\n'

def psin(t):                      # PICO-8 sin: inverted, argument in turns
    return -math.sin(2 * math.pi * t)

def fx(v):                        # 8.8 fixed point
    return int(math.floor(v * 256 + 0.5))

out = ['; generated by tools/make_data.py - do not edit\n']
out.append(dta('tile_flags', list(flags)))
# 8.8 sine, 256 steps per turn
sin88 = [fx(psin(i / 256)) for i in range(256)]
out.append(dta('sin_lo', [v & 255 for v in sin88]))
out.append(dta('sin_hi', [(v >> 8) & 255 for v in sin88]))
# orb ring: 8*cos / 8*sin, floored with the orb centre later
out.append(dta('ring_cos', [int(math.floor(8 * math.cos(2 * math.pi * i / 256) + 0.5)) for i in range(256)]))
out.append(dta('ring_sin', [int(math.floor(8 * psin(i / 256) + 0.5)) for i in range(256)]))
# balloon: flr(sin(offset)*2) for the top byte of the offset
out.append(dta('balloon_off', [math.floor(2 * psin(i / 256)) for i in range(256)]))
# fruit: flr(sin(off/40)*2.5)
out.append(dta('fruit_off', [math.floor(2.5 * psin(i / 40)) for i in range(40)]))
# fly_fruit: step = 0.5 + 0.05*k  -> spd.y = sin(step)*0.5 (8.8)
fly = [math.floor(math.floor(psin((32768 + 3277 * k) / 65536) * 65536 + 0.5) * 0.5) for k in range(20)]
out.append(dta('fly_spd_f', [v & 255 for v in fly]))
out.append(dta('fly_spd_lo', [(v >> 8) & 255 for v in fly]))
out.append(dta('fly_spd_hi', [(v >> 16) & 255 for v in fly]))
# key sprite: flr(9 + sin(frames/30) + 0.5)
out.append(dta('key_spr', [math.floor(9.5 + psin(f / 30)) for f in range(30)]))
# dead particles: sin(d/8)*3, cos(d/8)*3 in 8.8
dp_x = [fx(3 * psin(d / 8)) for d in range(8)]
dp_y = [fx(3 * math.cos(2 * math.pi * d / 8)) for d in range(8)]
out.append(dta('dead_sx_lo', [v & 255 for v in dp_x]))
out.append(dta('dead_sx_hi', [(v >> 8) & 255 for v in dp_x]))
out.append(dta('dead_sy_lo', [v & 255 for v in dp_y]))
out.append(dta('dead_sy_hi', [(v >> 8) & 255 for v in dp_y]))
# dead particle half size t/5 in 8.8 for t=0..10
out.append(dta('tfifth_lo', [fx(t / 5) & 255 for t in range(11)]))
out.append(dta('tfifth_hi', [fx(t / 5) >> 8 for t in range(11)]))

# Text and glyph mapping (ASCII -> glyph index, 255 = none)
amap = [255] * 128
for i, ch in enumerate(glyph_order):
    amap[ord(ch)] = i
out.append(dta('ascii_glyph', amap))

# PICO-8 palette (entry 16 is an opaque black used for colour 0 in fills)
PAL = [(0, 0, 0), (29, 43, 83), (126, 37, 83), (0, 135, 81), (171, 82, 54),
       (95, 87, 79), (194, 195, 199), (255, 241, 232), (255, 0, 77),
       (255, 163, 0), (255, 255, 39), (0, 231, 88), (41, 173, 255),
       (131, 118, 156), (255, 119, 168), (255, 204, 170), (0, 0, 0)]
out.append(dta('pal_r', [p[0] for p in PAL]))
out.append(dta('pal_g', [p[1] for p in PAL]))
out.append(dta('pal_b', [p[2] for p in PAL]))

# ---------------------------------------------------------------- sound
# Each sfx: 32 notes x 2 bytes, then speed, loop start, loop end, 0.
# note byte 0: pitch (0..63) | $40 if the noise waveform is used
# note byte 1: volume (0..7) | effect << 4
snd = bytearray()
for sid in range(64):
    b = 0x3200 + sid * 68
    for n in range(32):
        lo, hi = cart[b + n * 2], cart[b + n * 2 + 1]
        pitch = lo & 0x3f
        wave = ((lo >> 6) & 3) | ((hi & 1) << 2)
        vol = (hi >> 1) & 7
        eff = (hi >> 4) & 7
        snd += bytes([pitch | (0x40 if wave == 6 else 0), vol | (eff << 4)])
    snd += bytes([max(1, cart[b + 65]), cart[b + 66], cart[b + 67], 0])
(HERE / 'data' / 'sfx.bin').write_bytes(snd)
out.append('sfx_ptr_lo\n' + '\n'.join(f'        dta <(sfx_data+{i * 68})' for i in range(64)) + '\n')
out.append('sfx_ptr_hi\n' + '\n'.join(f'        dta >(sfx_data+{i * 68})' for i in range(64)) + '\n')
music = cart[0x3100:0x3200]
out.append(dta('music_data', list(music)))

# POKEY AUDF for PICO-8 pitch p (64 kHz clock); notes below the 8-bit range
# are raised by octaves.
audf = []
for p in range(64):
    f = 65.406 * 2 ** (p / 12)
    while 63921 / (2 * f) - 1 > 255:
        f *= 2
    audf.append(max(1, min(255, round(63921 / (2 * f) - 1))))
out.append(dta('pitch_audf', audf))

(HERE / 'gen' / 'tables.asm').write_text('\n'.join(out))
print('glyphs:', len(glyph_order), 'stage bytes:', len(stage), 'sfx bytes:', len(snd))
