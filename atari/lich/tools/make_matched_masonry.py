#!/usr/bin/env python3
"""Build connected scenery from the user's saved mockup matches; no rule edits."""
import json
from pathlib import Path
import lichdata as LD
H=LD.HERE
source=H/'data/matched-floor-source.json'
g=json.loads(source.read_text())
ref=json.loads((H/'editor/reference-assets.js').read_text().split('const MATCH_REFERENCE = ')[1].split(';\n',1)[0])
original=json.loads((H/'editor/art-packs.js').read_text().split('const CRYPT_ART = ')[1].rstrip(';\n'))['original']
def tile(n):return [r[n%16*8:n%16*8+8] for r in g['sheet'][n//16*8:n//16*8+8]]
def put(n,rows):
 x,y=n%16*8,n//16*8
 for i,r in enumerate(rows):g['sheet'][y+i]=g['sheet'][y+i][:x]+r+g['sheet'][y+i][x+8:]
tiles={int(n):tile(int(n)) for n in original}
before={n:rows[:] for n,rows in tiles.items()}
# Keep the user's paving and reuse their crack variants for the other floor families.
for n,base in [(36,1),(37,32),(38,33),(40,1),(41,33),(42,34)]:tiles[n]=tile(base)
# Wall front: four pixels of staggered dark brick, then four pixels of paving.
face=ref['cells'][2*35+8][:4]
for n,base in [(2,1),(35,32),(39,36),(43,40)]:tiles[n]=face+tiles[base][4:]
tiles[3]=face+['00000000']*4
# A continuous capstone band joins side walls to front brick faces. The front
# occupies 12 pixels across the wall and wall-foot cells, leaving 4 for paving.
brick=ref['cells'][2*35+8]
side=ref['cells'][6*35+1]
cap=ref['cells'][1*35+8][:4]
for mask in range(16):
 north,west,east,south=[bool(mask&bit) for bit in (1,2,4,8)]
 rows=[list(r) for r in (side if south else cap+brick[:4])]
 if south and (west or east):
  # Horizontal capstones continue through corners and T-junctions.
  rows[:4]=[list(r) for r in cap]
 if not south and north:
  # Return edges keep the side-wall column visible at the lower corner.
  for y in range(4,8):
   if not west:rows[y][:2]=list(side[y][:2])
   if not east:rows[y][6:]=list(side[y][6:])
 for y in range(8):
  if not west:rows[y][0]='0'
  if not east:rows[y][7]='0'
 tiles[48+mask]=[''.join(r) for r in rows]
previous_path=H/'editor/matched-masonry-art.js'
previous=json.loads(previous_path.read_text().split('const MATCHED_MASONRY_ART = ')[1].rstrip(';\n'))
previous_tiles=previous['migration_previous']
history=previous.get('migration_history',[previous_tiles])
if previous['id']!='matched-masonry-v4':history=history+[previous['tiles']]
changed={n:r for n,r in tiles.items() if r!=before[n]}
pack=dict(id='matched-masonry-v4',name='Matched Minifantasy masonry',tiles=tiles,credit='Minifantasy / Krishna Palacio. Adapted connected walls and paving from your saved matches. Non-commercial license.',migration_history=history,migration_previous=previous_tiles,migration_before={n:before[n] for n in changed},migration_tiles=changed)
(H/'editor/matched-masonry-art.js').write_text('// Generated by tools/make_matched_masonry.py\nconst MATCHED_MASONRY_ART = '+json.dumps(pack,separators=(',',':'))+';\n')
for n,r in tiles.items():put(n,r)
# Tile 35 is now a composite, not an exact screenshot crop. Preserve provenance
# without claiming its current pixels are an unmodified reference match.
g['reference_matches']['35']['adaptation']='Top four rows replaced with brick face; bottom four use matched paving.'
g['art_style']=pack['id'];g['matched_masonry_revision']=pack['id']
# Artwork regeneration must not reset the selected translation.
current=json.loads((H/'data/game.json').read_text())
if current.get('language'):
 for key in ['language','name','texts','windows']:g[key]=current[key]
 for kind in ['monsters','items']:
  for target,existing in zip(g[kind],current[kind]):target['name']=existing['name']
(H/'data/game.json').write_text(json.dumps(g,indent=2)+'\n')
print('Updated',len(changed),'scenery sprites; preserved rules, maps, entities and flags.')
