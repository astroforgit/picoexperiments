#!/usr/bin/env python3
"""The Demon Within walls/stairs + original Lich furniture.

Only selected non-wooden furniture is recolored. All wooden furniture pixels,
including worn versions, doors, chests and shelves, stay exactly original.
"""
import json
import re
import hashlib
import lichdata as LD

HERE=LD.HERE
source=HERE.parent.parent/'allgames'/'[RPG]'/'The Demon Within (v1.0.0b).p8'
text=source.read_bytes().decode('latin-1')
sheet=text.split('__gfx__\n',1)[1].split('__',1)[0].strip().splitlines()
def sprite(n):
    x,y=n%16*8,n//16*8
    return [r[x:x+8] for r in sheet[y:y+8]]
crypt=json.loads((HERE/'editor/art-packs.js').read_text().split('const CRYPT_ART = ',1)[1].rstrip(';\n'))
# Reset the whole themed environment set to the original Lich pixels first.
tiles={int(n):list(rows) for n,rows in crypt['original'].items()}
recolors={}
def recolor(ids,colors):
    for n in ids:
        tiles[n]=[''.join(colors.get(c,c) for c in r) for r in tiles[n]]
        recolors[n]=colors
# Charcoal masonry and metal, with the original shapes and highlights retained.
recolor([6,7,8,9,21,22,24,64,68,70,72,80,84,86,88],{'d':'5','1':'5'})
# Ceramic vessels: cyan glazes against charcoal shadows, never wooden surfaces.
recolor([26,27,28,29],{'d':'5','6':'c'})
# Cyan altar cloth and cold metal candle holders; warm flames remain unchanged.
recolor([25],{'d':'5','8':'c','2':'1'})
recolor([71,75,87,91],{'d':'5','e':'c'})
preserved_wood=[4,5,12,13,14,15,23,30,31,65,66,67,69,73,74,81,82,83,85,89,90]
imports={1:1,2:4,3:4,16:14,17:15}
for target,origin in imports.items():tiles[target]=sprite(origin)
# The styled-floor wall shadows must match the imported charcoal wall foot.
for n in [35,39,43]:tiles[n]=sprite(4)[:4]+tiles[n][4:]
signatures=list(map(int,re.search(r'wall_sig=explodeval\("([0-9,]+)"',text).group(1).split(',')))
ignored=list(map(int,re.search(r'wall_msk=explodeval\("([0-9,]+)"',text).group(1).split(',')))
wall_map={}
for mask in range(16):
    # Lich N/W/E/S bits -> source W/E/N/S bits; diagonals open.
    sig=(32 if mask&1 else 0)+(128 if mask&2 else 0)+(64 if mask&4 else 0)+(16 if mask&8 else 0)
    n=next(i+16 for i,(v,m) in enumerate(zip(signatures,ignored)) if sig|m==v|m)
    wall_map[48+mask]=n;tiles[48+mask]=sprite(n)
for n in preserved_wood:assert tiles[n]==crypt['original'][str(n)],n
for n,rows in tiles.items():assert len(rows)==8 and all(len(r)==8 and all(c in '0123456789abcdef' for c in r) for r in rows),n
pack={'id':'demon-v1','name':'The Demon Within','tiles':tiles,'source':'allgames/[RPG]/The Demon Within (v1.0.0b).p8',
      'source_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'wall_map':wall_map,'imports':imports,
      'recolors':recolors,'preserved_wood':preserved_wood}
(HERE/'editor/demon-art.js').write_text('// Generated by tools/make_demon_art.py. Source walls/stairs; original Lich furniture, selectively recolored.\nconst DEMON_ART = '+json.dumps(pack,separators=(',',':'))+';\n')
game=LD.load_game()
for n,rows in tiles.items():
    x,y=n%16*8,n//16*8
    for i,row in enumerate(rows):game['sheet'][y+i]=game['sheet'][y+i][:x]+row+game['sheet'][y+i][x+8:]
game['art_style']=game['art_revision']=pack['id']
(HERE/'data/game.json').write_text(json.dumps(game,indent=1)+'\n')
print(f'The Demon Within: 16 imported wall connections, source stairs, original furniture; {len(preserved_wood)} wooden tiles preserved exactly.')
