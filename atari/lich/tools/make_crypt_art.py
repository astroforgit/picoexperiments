def read_tile(sheet,n):
    x,y=n%16*8,n//16*8
    return [row[x:x+8] for row in sheet[y:y+8]]


def put_tile(sheet,n,rows):
    x,y=n%16*8,n//16*8
    for dy,row in enumerate(rows):sheet[y+dy]=sheet[y+dy][:x]+row+sheet[y+dy][x+8:]

