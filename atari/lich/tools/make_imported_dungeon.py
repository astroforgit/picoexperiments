#!/usr/bin/env python3
"""Select a complete environment assembled from the local imported art packs."""
import json
import lichdata as LD
H=LD.HERE
def read(file,const):return json.loads((H/'editor'/file).read_text().split('const '+const+' = ')[1].rstrip(';\n'))
chroma=read('chroma-art.js','CHROMA_ART');mini=read('minifantasy-art.js','MINIFANTASY_ART');alchemy=read('alchemy-art.js','ALCHEMY_ART')
tiles={k:v[:] for k,v in chroma['tiles'].items()}
# Maintain complete animation/consumed groups and all connected wall shapes.
groups=[(mini,[12,13,14,15,24,27,29,68,84,70,86,69,85,71,75]),(alchemy,[21,22,25,26,27,28,29,72,88])]
for pack,ids in groups:
 for n in ids:tiles[str(n)]=pack['tiles'][str(n)]
# Candles and their spent states share the imported metal colors.
for live,spent in [(71,87),(75,91)]:
 tiles[str(spent)]=[''.join({'a':'5','9':'5','7':'6','f':'5'}.get(c,c) for c in r) for r in tiles[str(live)]]
pack=dict(id='imported-dungeon-v1',name='Imported Dungeon',tiles=tiles,
 credit='Mystic Chroma / PetricakeGames; Minifantasy / Krishna Palacio (non-commercial only, attribution required); supplied Farm Sim alchemy assets. See ASSET-CREDITS.txt and Minifantasy-FreeLicense.txt.',
 description='Active combined environment: Chroma walls, stairs and themed furniture; Minifantasy wooden and stone props; alchemy well, altar and vessels.',
 components=[chroma['id'],mini['id'],alchemy['id']])
(H/'editor/imported-dungeon-art.js').write_text('// Generated by tools/make_imported_dungeon.py.\nconst IMPORTED_DUNGEON_ART = '+json.dumps(pack,separators=(',',':'))+';\n')
g=LD.load_game()
for key,rows in tiles.items():
 n=int(key);x,y=n%16*8,n//16*8
 for i,r in enumerate(rows):g['sheet'][y+i]=g['sheet'][y+i][:x]+r+g['sheet'][y+i][x+8:]
g['art_style']=g['art_revision']=pack['id']
(H/'data/game.json').write_text(json.dumps(g,indent=1)+'\n')
print('Imported Dungeon active:',len(tiles),'environment tiles. Monsters and rules unchanged.')
