#!/usr/bin/env python3
"""Convert selected local atlas regions/objects to optional PICO 8x8 tile packs."""
import json,hashlib
from PIL import Image
import lichdata as LD
H=LD.HERE
base=json.loads((H/'editor/art-packs.js').read_text().split('const CRYPT_ART = ')[1].rstrip(';\n'))['original']
pal=[(0,0,0),(29,43,83),(126,37,83),(0,135,81),(171,82,54),(95,87,79),(194,195,199),(255,241,232),(255,0,77),(255,163,0),(255,236,39),(0,228,54),(41,173,255),(131,118,156),(255,119,168),(255,204,170)]
manifest=[]
def converted(path,region=None):
 im=Image.open(path).convert('RGBA')
 if region:im=im.crop(region)
 bbox=im.getbbox()
 if bbox:im=im.crop(bbox)
 w,h=im.size;scale=min(8/w,8/h);nw,nh=max(1,round(w*scale)),max(1,round(h*scale));im=im.resize((nw,nh),Image.NEAREST)
 rows=[list('00000000') for _ in range(8)];ox=(8-nw)//2;oy=8-nh
 for y in range(nh):
  for x in range(nw):
   r,g,b,a=im.getpixel((x,y))
   if a<128:continue
   k=min(range(1,16),key=lambda k:sum((v-c)**2 for v,c in zip((r,g,b),pal[k])))
   rows[oy+y][ox+x]=hex(k)[2:]
 manifest.append(dict(path=str(path.relative_to(H)),sha256=hashlib.sha256(path.read_bytes()).hexdigest(),region=region))
 return [''.join(r) for r in rows]
def pack(id,name):return dict(id=id,name=name,tiles={int(k):v[:] for k,v in base.items()})
def recolor(p,ids,m):
 for n in ids:p['tiles'][n]=[''.join(m.get(c,c) for c in r) for r in p['tiles'][n]]
def publish(p,const,file):
 p['sources']=manifest[:];manifest.clear()
 (H/'editor'/file).write_text('// Generated by tools/make_asset_packs.py; source attribution stored in pack.\nconst '+const+' = '+json.dumps(p,separators=(',',':'))+';\n')
# Same atlas geometry as Mystic Acid, with its separate Chroma palette.
p=pack('mystic-chroma-v1','Mystic Chroma');src=H/'assets/MysticChroma_Basics.png'
recolor(p,range(48,64),{'e':'c','d':'1','6':'d','5':'1'})
recolor(p,[2,3,35,39,43,16,17],{'d':'c','6':'d','5':'1'})
recolor(p,[4,5,12,13,14,15,23,30,31,65,66,67,69,73,74,81,82,83,85,89,90],{'4':'8','2':'2','9':'f','a':'7','d':'c'})
recolor(p,[6,7,8,9,21,22,24,25,26,27,28,29,64,68,70,71,72,75,80,84,86,87,88,91],{'d':'c','6':'d','5':'1','8':'9','2':'4'})
p['tiles'][13]=converted(src,(32,64,48,80));p['tiles'][69]=converted(src,(48,64,64,80))
p['credit']='Mystic Chroma / PetricakeGames; adapted to the PICO palette.'
publish(p,'CHROMA_ART','chroma-art.js')
# Small furniture in this atlas already has readable eight-pixel silhouettes.
p=pack('minifantasy-v1','Minifantasy Dungeon');root=H/'assets/Minifantasy_Dungeon_v2.3_Free_Version/Minifantasy_Dungeon_v2.3_Free_Version/Minifantasy_Dungeon_Assets';src=root/'Props/Props.png'
regions={13:(8,8,16,16),12:(40,8,48,16),27:(136,8,144,16),29:(144,8,152,16),24:(120,8,128,16),72:(128,8,136,16),69:(152,24,160,40),85:(168,24,176,40),68:(24,48,32,64),84:(24,72,32,88),70:(80,48,88,64),86:(80,72,88,88),14:(8,24,24,40),15:(8,24,24,40)}
for n,r in regions.items():p['tiles'][n]=converted(src,r)
p['tiles'][71]=converted(root/'Props/Animated_Props/Candle.png',(0,0,8,16))
p['tiles'][75]=converted(root/'Props/Animated_Props/Torch.png',(0,0,16,24))
# Brick samples from the dungeon atlas supply matching wall faces.
brick=converted(root/'Tileset/Tileset.png',(48,16,56,24))
recolor(p,range(48,64),{'e':'5','d':'5','6':'6','1':'1'})
for n in range(48,64):
 if not (n-48)&8:p['tiles'][n][5:8]=brick[3:6]
p['credit']='Minifantasy by Krishna Palacio. Free license: non-commercial projects only; attribution required. See bundled Minifantasy-FreeLicense.txt.'
publish(p,'MINIFANTASY_ART','minifantasy-art.js')
# Larger objects become readable single-cell alchemy furniture.
p=pack('alchemy-v1','Alchemy Workshop');root=H/'assets/Farm Sim Asset Pack/potion and poison asset pack'
for n,name in {13:'Alchemist’s Vault Jar',15:'Alchemist Supply Cabinet',22:'Elder Cauldron',25:'Golden Ritual Lamp',27:'Royal Medicine Flask',29:'Shadow Venom Bottle',72:'Crimson Health Elixir',68:'Grand Alchemist Alembic',24:'Copper Alchemy Still'}.items():
 p['tiles'][n]=converted(root/(name+'.png'))
# Consumed variants retain their silhouette, with subdued contents.
for dst,src in [(12,13),(14,15),(21,22),(26,27),(28,29),(88,72),(84,68)]:
 p['tiles'][dst]=[''.join({'8':'2','9':'4','a':'5','b':'3','c':'1','7':'6','f':'5'}.get(c,c) for c in r) for r in p['tiles'][src]]
p['credit']='Adapted from the supplied Farm Sim Asset Pack. Objects are cosmetic alternatives; existing Lich interactions are unchanged.'
publish(p,'ALCHEMY_ART','alchemy-art.js')
print('Imported three optional environment packs: Mystic Chroma, Minifantasy Dungeon, Alchemy Workshop.')
