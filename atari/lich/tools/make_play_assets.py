#!/usr/bin/env python3
"""Decode the cartridge font, title map and sound effects for the JS play mode."""
import json
import lichdata as LD
cart = LD.cart_bytes()
font = {key: dict(pixels=px, width=w) for key, px, w in LD.parse_font(LD.lua_source())}
title = [[cart[0x2000 + y * 128 + x] for x in range(112, 128)] for y in range(16)]
sfx = []
for i in range(64):
    base = 0x3200 + i * 68
    notes = []
    for n in range(32):
        v = int.from_bytes(cart[base+n*2:base+n*2+2], 'little')
        notes.append([v & 63, (v >> 6) & 7, (v >> 9) & 7, (v >> 12) & 7])
    sfx.append(dict(speed=cart[base+65], notes=notes))
text = '// Generated by tools/make_play_assets.py from the original cartridge.\n'
for name, value in [('PLAY_FONT', font), ('PLAY_TITLE', title), ('PLAY_SFX', sfx)]:
    text += 'const ' + name + ' = ' + json.dumps(value, separators=(',', ':')) + ';\n'
(LD.HERE / 'editor' / 'play-font.js').write_text(text)
