#!/usr/bin/env python3
"""Adapt the supplied Mystic Acid atlas into a selectable 8x8 Lich art pack.

Pixel extraction and palette conversion target the existing PICO/VBXE tile format.
The source PNG and the selected game sheet are never modified.
"""
import json,hashlib
from PIL import Image
import lichdata as LD
H=LD.HERE
source=H/'MysticAcid_basics_PetricakeGames.png'
im=Image.open(source).convert('RGBA')
palette={(255,255,255):'7',(176,121,148):'d',(166,83,112):'2',(162,165,170):'6',(133,89,103):'4',(122,165,134):'3',(119,149,158):'d',(88,87,140):'1',(73,45,84):'1',(60,63,79):'1',(38,31,51):'0',(204,204,204):'6',(199,142,119):'f',(129,204,136):'b',(123,76,125):'2',(113,120,130):'5',(102,58,94):'2',(93,130,107):'3',(88,104,117):'5'}
def pixel(x,y):
 r,g,b,a=im.getpixel((x,y));return palette[(r,g,b)] if a else '0'
def extract(x,y,w=8,h=8):
 return [''.join(pixel(x+min(w-1,int((xx+.5)*w/8)),y+min(h-1,int((yy+.5)*h/8))) for xx in range(8)) for yy in range(8)]
base=json.loads((H/'editor/art-packs.js').read_text().split('const CRYPT_ART = ')[1].rstrip(';\n'))['original']
tiles={int(k):v[:] for k,v in base.items()}
def colors(ids,mapping):
 for n in ids:tiles[n]=[''.join(mapping.get(c,c) for c in r) for r in tiles[n]]
def put(n,rows):
 assert len(rows)==8 and all(len(r)==8 and set(r)<=set('0123456789abcdef') for r in rows)
 tiles[n]=rows
# Keep all 16 original wall junction silhouettes; sample the atlas brick face.
brick=extract(32,16)
for n in range(48,64):
 rows=[]
 for y,row in enumerate(tiles[n]):
  rows.append(''.join(('3' if c=='e' else '1') if y<5 and c!='0' else (('6' if (x+y)%4==0 else '5') if c in '6d' else '1') if y>=5 and c!='0' else '0' for x,c in enumerate(row)))
 if not (n-48)&8:
  rows[5]=brick[0];rows[6]=brick[5];rows[7]=brick[7]
 put(n,rows)
# Source stone cap and green seam repeated above the existing floor shadows.
for n in [2,3,35,39,43]:
 put(n,['56565656','33333333','15111511','11111111']+tiles[n][4:])
colors([16,17],{'d':'5','6':'6','5':'3'})
put(16,['56666665','53111135','53d11135','53d00035','53d15035','53d15035','53d15035','53333335'])
# Original Lich furniture adapted to the atlas's plum wood, mint trim and metal.
wood=[4,5,12,13,14,15,23,30,31,65,66,67,69,73,74,81,82,83,85,89,90]
colors(wood,{'4':'2','2':'1','9':'4','a':'f','d':'5','6':'d'})
colors([6,7,8,9,21,22,24,64,68,70,72,80,84,86,88],{'d':'5','6':'6','1':'3','5':'1'})
colors([26,27,28,29],{'d':'3','6':'b','5':'5'})
colors([25],{'8':'3','2':'1','d':'5','4':'2','7':'6'})
colors([71,75,87,91],{'d':'5','6':'6','9':'3','a':'b','e':'3'})
# Two-panel chest/cabinet directly adapted from the 16x16 atlas object.
put(13,extract(32,64,16,16))
put(12,['00000000','05222250','52111125','51111115','52555525','52222225','05555550','00000000'])
# The atlas's plum table silhouette, reduced to one tile; matching worn state.
put(69,extract(48,64,16,16))
put(85,['00000000','05555550','05222250','00122100','00111000','00101000','00100000','00000000'])
# Mint stone lid and a plum/rust inlay echo the atlas decorative plaque.
put(70,['00000000','00000000','56666650','53b33b35','53122135','53b33b35','05555550','00000000'])
put(68,['00366300','00566500','000ff000','00024000','00544500','00355300','00666600','00555500'])
pack=dict(id='mystic-acid-v1',name='Mystic Acid',tiles=tiles,source=source.name,source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),description='Adapted from the supplied PetricakeGames atlas: slate masonry, mint edges, plum furniture. PICO-8 palette; original Lich wall connectivity.',extracted_objects={'13':[32,64,16,16],'69':[48,64,16,16]},brick_source=[32,16,8,8])
(H/'editor/mystic-art.js').write_text('// Generated by tools/make_mystic_art.py. Source: MysticAcid_basics_PetricakeGames.png; 8x8/palette adaptations.\nconst MYSTIC_ART = '+json.dumps(pack,separators=(',',':'))+';\n')
print('Mystic Acid:',len(tiles),'environment tiles; existing selected artwork unchanged.')
