#!/usr/bin/env python3
"""Adapt the local Crocolike cartridge's actual walls/stairs to Lich King.

Crocolike's 8-neighbour wall signatures are mapped to Lich's 4-neighbour masks.
Environment IDs, flags and gameplay data are retained. Furniture combines the
existing Lich redesign with Crocolike's rust/plum and emerald/lime colors.
"""
import json
import re
import hashlib
import lichdata as LD

HERE=LD.HERE
source=HERE.parent.parent/'allgames'/'[RPG]'/'Crocolike.p8'
text=source.read_bytes().decode('latin-1')
sheet=text.split('__gfx__\n',1)[1].split('__',1)[0].strip().splitlines()

def sprite(n):
    x,y=n%16*8,n//16*8
    return [r[x:x+8] for r in sheet[y:y+8]]

# Reuse the previous original furniture shapes without rewriting that art pack.
crypt_text=(HERE/'editor/art-packs.js').read_text()
crypt=json.loads(crypt_text.split('const CRYPT_ART = ',1)[1].rstrip(';\n'))
tiles={int(n):list(rows) for n,rows in crypt['tiles'].items()}

def recolor(n,colors):
    tiles[n]=[''.join(colors.get(c,c) for c in r) for r in tiles[n]]

# Crocolike furniture is outlined in lime with emerald body/shadow colors.
wood={'4':'3','9':'b','a':'b','d':'3','6':'b','5':'3','1':'1','c':'b'}
stone={'d':'4','6':'9','5':'2','3':'2','c':'b','1':'1'}
for n in [4,5,7,9,12,13,14,15,23,25,27,29,30,31,65,66,67,69,73,74,81,82,83,85,89,90]:recolor(n,wood)
for n in [6,8,21,22,24,64,68,70,72,80,84,86,88]:recolor(n,stone)
for n in [26,28]:recolor(n,{'5':'3','3':'3','1':'1'})
for n in [71,75,87,91]:recolor(n,{'6':'b','d':'3','5':'3','9':'9','a':'a'})

# Direct cartridge tiles, without palette conversion or redrawing.
imports={1:1,2:4,3:4,4:13,5:13,12:9,13:10,16:14,17:15,27:7,29:8,
         32:74,33:70,34:71,36:72,37:73,38:75,40:68,41:76,42:1}
for target,origin in imports.items():tiles[target]=sprite(origin)
for target,base in [(35,32),(39,36),(43,40)]:tiles[target]=sprite(4)[:2]+tiles[base][2:]

line=next(line for line in text.splitlines() if 'crv_sig,crv_msk' in line)
arrays=[list(map(int,s.split(','))) for s in re.findall(r'explodeval\("([0-9,]+)"\)',line)]
signatures,ignored=arrays[-2:]
wall_map={}
for mask in range(16):
    # Lich: N=1,W=2,E=4,S=8. Crocolike: W=128,E=64,N=32,S=16,
    # NE=8,SE=4,SW=2,NW=1. Diagonals are open for a one-tile-wide wall.
    sig=(32 if mask&1 else 0)+(128 if mask&2 else 0)+(64 if mask&4 else 0)+(16 if mask&8 else 0)
    match=next((i+16 for i,(value,ignore) in enumerate(zip(signatures,ignored)) if sig|ignore==value|ignore),None)
    assert match is not None,mask
    wall_map[48+mask]=match
    tiles[48+mask]=sprite(match)

for n,rows in tiles.items():
    assert len(rows)==8 and all(len(r)==8 and all(c in '0123456789abcdef' for c in r) for r in rows),n
pack={'id':'crocolike-v1','name':'Crocolike Dungeon','tiles':tiles,
      'source':'allgames/[RPG]/Crocolike.p8','source_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),
      'wall_map':wall_map,'imports':imports}
(HERE/'editor/crocolike-art.js').write_text('// Generated by tools/make_crocolike_art.py. Wall, stair and selected prop pixels from the local Crocolike cartridge.\nconst CROCO_ART = '+json.dumps(pack,separators=(',',':'))+';\n')
game=LD.load_game()
for n,rows in tiles.items():
    x,y=n%16*8,n//16*8
    for i,r in enumerate(rows):game['sheet'][y+i]=game['sheet'][y+i][:x]+r+game['sheet'][y+i][x+8:]
game['art_style']=game['art_revision']=pack['id']
(HERE/'data/game.json').write_text(json.dumps(game,indent=1)+'\n')
print(f'Crocolike Dungeon: {len(tiles)} environment tiles; 16 exact source wall tiles and source stairs 14/15.')
print('Wall mapping:',wall_map)
