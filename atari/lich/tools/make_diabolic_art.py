#!/usr/bin/env python3
"""Dark diabolic edits to original Lich environment pixels; no imported terrain."""
import json
import lichdata as LD

HERE = LD.HERE
crypt = json.loads((HERE/'editor/art-packs.js').read_text().split('const CRYPT_ART = ', 1)[1].rstrip(';\n'))
tiles = {int(n): list(rows) for n, rows in crypt['original'].items()}

def recolor(ids, colors):
    for n in ids:
        tiles[n] = [''.join(colors.get(c, c) for c in row) for row in tiles[n]]

def pixels(n, edits):
    rows = [list(row) for row in tiles[n]]
    for x, y, color in edits:
        rows[y][x] = color
    tiles[n] = [''.join(row) for row in rows]

# Keep every original wall connection and silhouette. The original pink edge
# is navy in the lit game palette; use plum here so the crimson tint survives.
recolor(range(48, 64), {'e':'1', 'd':'2', '6':'5'})
# Small cracks only inside masonry, never across a connection seam.
for n in range(48, 64):
    if not (n-48)&8:
        pixels(n, [(2,5,'1'), (3,6,'2'), (4,7,'1')])
# Original floor shadows and stairs, with matching masonry and restrained embers.
recolor([2,3,35,39,43], {'d':'5'})
recolor([16,17], {'d':'5', '6':'d'})
pixels(16, [(3,0,'2'),(4,0,'8')])
pixels(17, [(2,3,'2')])
recolor([6,7,8,9,21,22,24,64,68,70,72,80,84,86,88], {'d':'5', '6':'d'})
recolor([26,27,28,29], {'d':'5','6':'2'})
recolor([25], {'d':'5','2':'2','8':'8'})
# Pointed statue crown, glowing eyes, and a smaller remnant on its broken state.
pixels(68, [(1,0,'5'),(6,0,'5'),(2,2,'8'),(5,2,'8')])
pixels(84, [(3,0,'5'),(3,2,'2')])
# Inverted cross engraved into the original sarcophagus; worn one stays worn.
pixels(70, [(2,3,'2'),(2,4,'8'),(1,5,'2'),(2,5,'8'),(3,5,'2')])
pixels(86, [(3,5,'2'),(4,5,'8')])
pixels(72, [(3,3,'2'),(4,4,'8'),(3,5,'2')])
# Tiny points on the existing iron grille; warm amber/red candles.
pixels(64, [(2,2,'5'),(4,2,'5'),(6,2,'5')])
recolor([71,75,87,91], {'d':'5','e':'8','a':'9','9':'8'})
pixels(25, [(3,5,'8'),(4,6,'2')])
# Wood remains original brown; just an iron clasp on the chest.
pixels(13, [(3,4,'5'),(4,4,'8')])

# Charred oak: retain brown grain over near-black and deep claret recesses.
wood = [4,5,12,13,14,15,23,30,31,65,66,67,69,73,74,81,82,83,85,89,90]
recolor(wood, {'9':'4','a':'9','2':'1','6':'5','7':'d'})
for n in wood:
    rows = tiles[n]
    for y,row in enumerate(rows):
        for x,c in enumerate(row):
            if c=='4' and (x+2*y)%4==0:
                pixels(n, [(x,y,'2')])
# Dark iron and ashen stone. Retain a few bright edges for legibility.
recolor([6,7,8,9,21,22,24,68,70,72,84,86,88], {'d':'5','5':'1'})
for n in [21,22,24,68,70]:
    for x,y in [(2,1),(3,1),(2,5)]:
        if tiles[n][y][x]!='0': pixels(n,[(x,y,'5')])
# A clearly horned idol with ember eyes and a narrow fanged jaw.
tiles[68]=['01000010','01511510','00188100','00155100','00021000','00155100','00511500','00111100']
# Blood-red altar drape with a pale inverted sigil, edged in dark iron.
tiles[25]=['00000000','01000010','55555555','52111225','52818225','12888221','12218221','12222221']
# Blackened tomb with an engraved crimson cross and restrained edge highlights.
tiles[70]=['00000000','00000000','00000000','55155510','51211510','52822510','11111110','00000000']
# Matching worn carvings, urn seals, burnt-out candle stands, and iron spikes.
pixels(84,[(3,2,'8'),(3,3,'2')])
recolor([26,27,28,29,72,88], {'5':'1'})
pixels(27,[(3,3,'2'),(4,4,'8')])
recolor([46,47], {'f':'5','7':'d','2':'1'})
# A stone arch with a blood-red keystone frames the original stair opening.
pixels(16,[(1,0,'1'),(2,0,'2'),(3,0,'8'),(4,0,'2'),(5,0,'1')])

for n, rows in tiles.items():
    assert len(rows)==8 and all(len(r)==8 and set(r)<=set('0123456789abcdef') for r in rows), n
pack = {'id':'diabolic-v2', 'name':'Diabolic Crypt', 'tiles':tiles,
        'source':'Original Curse of the Lich King environment sprites',
        'description':'Charcoal masonry, charred oak, blood-red altar, horned idol and engraved tombs.'}
(HERE/'editor/diabolic-art.js').write_text('// Generated by tools/make_diabolic_art.py from original Lich sprites.\nconst DIABOLIC_ART = '+json.dumps(pack,separators=(',',':'))+';\n')
game = LD.load_game()
for n, rows in tiles.items():
    x,y = n%16*8,n//16*8
    for i,row in enumerate(rows):
        game['sheet'][y+i] = game['sheet'][y+i][:x]+row+game['sheet'][y+i][x+8:]
game['art_style'] = game['art_revision'] = pack['id']
(HERE/'data/game.json').write_text(json.dumps(game,indent=1)+'\n')
print('Diabolic Crypt: original environment restored with darker palette and stronger demonic details.')
