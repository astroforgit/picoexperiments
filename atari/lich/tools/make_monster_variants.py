#!/usr/bin/env python3
"""Build optional four-frame variants without changing the selected game art."""
import json
import lichdata as LD
H=LD.HERE
g=LD.load_game();original=LD.default_game()
entries=json.loads((H/'editor/bestiary-pack.js').read_text().split('const BESTIARY_PACK = ')[1].rstrip(';\n'))
def tile(sheet,n):
 x,y=n%16*8,n//16*8
 return [r[x:x+8] for r in sheet[y:y+8]]
packs={}
for i,m in enumerate(g['monsters']):
 if i==0 or m['prop']:continue
 key=m.get('catalog_key','lich-'+str(i+1))
 entry=next((e for e in entries if e['key']==key),None)
 frames=entry['frames'] if entry else [tile(original['sheet'],m['anim']+k) for k in range(4)]
 name=m['name'].lower()
 # Coherent ramps retain eyes/highlights while changing the material or skin.
 if any(w in name for w in ['slime','slaim','snek','croco','goblin','troll']):
  palette={'3':'2','b':'e','a':'f','8':'e','2':'1','4':'2','9':'e'};label='Venom violet'
 elif any(w in name for w in ['ghost','goast','gastly','haunt','gengar','drif','litwick']):
  palette={'1':'3','d':'b','7':'a','6':'b','8':'9','a':'7'};label='Spectral jade'
 elif any(w in name for w in ['skeleton','bone','danser','knight','berserker','zomb']):
  palette={'6':'c','7':'7','5':'1','d':'c','4':'5','3':'1','b':'c','2':'1','8':'c'};label='Frostbound'
 elif any(w in name for w in ['bat','bads','golbat','zubat','rat','scorp','skorpy','manki']):
  palette={'1':'2','d':'4','7':'f','3':'4','b':'9','8':'9','2':'4','4':'2','9':'f','a':'7'};label='Ember hide'
 else:
  palette={'1':'1','2':'3','8':'c','9':'b','a':'7','d':'5','6':'c','7':'f','4':'5','3':'2','b':'e','f':'d'};label='Twilight'
 variants=[]
 for frame in frames:
  px=[list(''.join(palette.get(c,c) for c in row)) for row in frame]
  occupied=[(x,y) for y,row in enumerate(frame) for x,c in enumerate(row) if c!='0']
  if occupied:
   # A small crest or a ragged tip, attached to the existing outline. Keep 8x8 bounds.
   top=min(y for x,y in occupied);xs=[x for x,y in occupied if y==top]
   if top>0:
    px[top-1][xs[0]]='5' if label=='Frostbound' else '2'
    if len(xs)>2:px[top-1][xs[-1]]='c' if label=='Frostbound' else '5'
   else:
    x,y=next(((x,y) for x,y in occupied if x>0 and frame[y][x-1]=='0'),occupied[0])
    if x>0 and frame[y][x-1]=='0':px[y][x-1]='5'
   # Give one edge a deliberate highlight; maintain transparent background.
   x,y=max(occupied,key=lambda p:(p[1],-p[0]));px[y][x]='c' if label=='Frostbound' else 'd'
  rows=[''.join(r) for r in px]
  assert rows!=frame and len(rows)==8 and all(len(r)==8 for r in rows)
  variants.append(rows)
 packs[key]=dict(name=m['name'],label=label,base=frames,alternate=variants)
(H/'editor/monster-variants-pack.js').write_text('// Generated by tools/make_monster_variants.py. Optional original pixel variants.\nconst MONSTER_VARIANTS = '+json.dumps(packs,separators=(',',':'))+';\n')
print('Optional variants:',len(packs),'monsters,',len(packs)*4,'animation frames.')
