#!/usr/bin/env python3
"""Install four native 8x16 Minifantasy props with a one-cell collision base."""
import json
from PIL import Image
import lichdata as LD
H=LD.HERE;g=LD.load_game()
src=H/'assets/Minifantasy_Dungeon_v2.3_Free_Version/Minifantasy_Dungeon_v2.3_Free_Version/Minifantasy_Dungeon_Assets/Props/Props.png'
im=Image.open(src).convert('RGBA')
pal=[(0,0,0),(29,43,83),(126,37,83),(0,135,81),(171,82,54),(95,87,79),(194,195,199),(255,241,232),(255,0,77),(255,163,0),(255,236,39),(0,228,54),(41,173,255),(131,118,156),(255,119,168),(255,204,170)]
def rows(x,y):
 out=[]
 for yy in range(y,y+8):
  r=''
  for xx in range(x,x+8):
   rgba=im.getpixel((xx,yy));k=0 if rgba[3]<128 else min(range(1,16),key=lambda k:sum((a-b)**2 for a,b in zip(rgba[:3],pal[k])))
   r+=hex(k)[2:]
  out.append(r)
 return out
specs=[(68,376,24,48,'Stone idol'),(84,377,24,72,'Worn idol'),(70,378,80,48,'Armored monument'),(86,379,80,72,'Worn monument')]
pack={}
for base,top,x,y,name in specs:
 pack[str(base)]={'top':top,'enabled':True,'name':name,'baseRows':rows(x,y+8),'topRows':rows(x,y)}
(H/'editor/tall-props-pack.js').write_text('// Minifantasy by Krishna Palacio; non-commercial free license. Generated by tools/make_tall_props.py.\nconst TALL_PROPS_PACK = '+json.dumps(pack,separators=(',',':'))+';\n')
for key,p in pack.items():
 for n,sheet,rs in [(int(key),g['sheet'],p['baseRows']),(p['top']-256,g['sheet2'],p['topRows'])]:
  x,y=n%16*8,n//16*8
  for i,r in enumerate(rs):sheet[y+i]=sheet[y+i][:x]+r+sheet[y+i][x+8:]
g['overhangs']={k:{key:p[key] for key in ['top','enabled','name']} for k,p in pack.items()}
g['overhang_revision']='tall-v1'
(H/'data/game.json').write_text(json.dumps(g,indent=1)+'\n')
