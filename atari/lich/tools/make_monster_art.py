#!/usr/bin/env python3
"""Replace original enemy animation pixels, without changing entity definitions.

Each source sequence is copied into the original Lich monster's four sprite
slots, preserving map codes, stats, abilities, colors, names and spawning rules.
"""
import json
import hashlib
import lichdata as LD

HERE=LD.HERE
ROOT=HERE.parent.parent
original=LD.default_game()
game=LD.load_game()
choices=[
    (2,'Crocolike','slaim',[192,193,194,195]),
    (3,'The Demon Within (v1.0.0b)','carnivorous slime',[224,225,226,227]),
    (14,'The Demon Within (v1.0.0b)','corrupt wizard',[208,209,210,211]),
    (15,'The Demon Within (v1.0.0b)','lesser demon',[244,245,246,247]),
    (16,'Porklike','creature 5',[131,132,131,133]),
    (17,'The Demon Within (v1.0.0b)','berserker',[196,197,198,199]),
    (19,'Crocolike','danser',[228,229,230,231]),
    (22,'Crocolike','skorpy',[200,201,202,203]),
    (23,'BulbaRogue','haunter',[212,213,214,215]),
    (24,'Crocolike','death',[232,233,234,235]),
]
def tile(sheet,n):
    x,y=n%16*8,n//16*8
    return [r[x:x+8] for r in sheet[y:y+8]]
pack={'id':'guest-monsters-v1','name':'Guest monster sprites','entries':[],'tiles':{},'original':{},'sources':{}}
for ident,cart,name,frames in choices:
    source=ROOT/'allgames'/'[RPG]'/(cart+'.p8')
    rows=source.read_bytes().decode('latin-1').split('__gfx__\n',1)[1].split('__',1)[0].strip().splitlines()
    pack['sources'][cart]={'path':str(source.relative_to(ROOT)),'sha256':hashlib.sha256(source.read_bytes()).hexdigest()}
    base=original['monsters'][ident-1]['anim']
    # Refuse to silently rewrite an imported or relocated monster in source data.
    assert game['monsters'][ident-1]['anim']==base,(ident,'animation slot was edited')
    pack['entries'].append({'id':ident,'base':base,'role':original['monsters'][ident-1]['name'],'cart':cart,'name':name,'frames':frames})
    for k,n in enumerate(frames):
        target=base+k;pixels=tile(rows,n)
        assert len(pixels)==8 and all(len(r)==8 and all(c in '0123456789abcdef' for c in r) for r in pixels)
        pack['tiles'][target]=pixels;pack['original'][target]=tile(original['sheet'],target)
        x,y=target%16*8,target//16*8
        for dy,row in enumerate(pixels):game['sheet'][y+dy]=game['sheet'][y+dy][:x]+row+game['sheet'][y+dy][x+8:]
game['monster_art_style']=game['monster_art_revision']=pack['id']
(HERE/'data/game.json').write_text(json.dumps(game,indent=1)+'\n')
(HERE/'editor/monster-art-pack.js').write_text('// Generated by tools/make_monster_art.py. Guest animation pixels from the bundled PICO-8 cartridges; Lich game rules unchanged.\nconst MONSTER_ART = '+json.dumps(pack,separators=(',',':'))+';\n')
print(f'Guest sprites: {len(choices)} enemies, {len(pack["tiles"])} frames. Entity definitions unchanged.')
