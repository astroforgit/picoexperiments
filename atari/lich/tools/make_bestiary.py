#!/usr/bin/env python3
"""Build additive enemy catalog; original Lich creatures retain their slots/stats."""
import json
import lichdata as LD
H=LD.HERE
g=LD.load_game()
old=json.loads((H/'editor/monster-art-pack.js').read_text().split('const MONSTER_ART = ')[1].rstrip(';\n'))
def put(sheet,n,rows):
 x,y=n%16*8,n//16*8
 for i,r in enumerate(rows):sheet[y+i]=sheet[y+i][:x]+r+sheet[y+i][x+8:]
def tile(sheet,n):
 x,y=n%16*8,n//16*8
 return [r[x:x+8] for r in sheet[y:y+8]]
# Restore only recognized replacement frames; preserve hand-painted art.
for n,rows in old['original'].items():
 n=int(n)
 if tile(g['sheet'],n)==old['tiles'][str(n)]:put(g['sheet'],n,rows)
# HP, attack and abilities follow the Lich scale (hero begins at 6 HP / 3 attack).
stats=[('a marsh slime',2,1,1,[]),('a carrion slime',7,1,2,[]),('a fallen mage',10,0,5,['bolt']),('a lesser demon',11,1,3,['blink']),('a thornling',5,1,2,[]),('a berserker',20,3,6,[]),('a bone dancer',10,2,4,[]),('a scorpion',5,0,4,['poison']),('a night haunter',11,1,7,['paralyze']),('a dread reaper',26,3,8,['hunter'])]
entries=[]
for i,(e,(name,hp,atk,depth,abilities)) in enumerate(zip(old['entries'],stats)):
 entries.append(dict(key='guest-'+str(i),name=name,hp=hp,atk=atk,depth=depth,abilities=abilities,range=4 if 'bolt' in abilities else 1,sight=5 if 'bolt' in abilities else 4,col=8,from_source=e['cart']+' / '+e['name'],frames=[old['tiles'][str(e['base']+k)] for k in range(4)]))
# Original eight-pixel designs using fantasy archetypes, not copied game characters.
designs=[
 ('an ash bat',3,1,1,[],['00000000','01000100','01505100','15585510','01555100','00151000','00010000','00000000']),
 ('a grave goblin',8,2,3,[],['03000300','03bb3300','00b8b000','00333000','05333500','00333000','00303000','00505000']),
 ('a bone hound',14,2,5,['pounce'],['00000000','06006000','06666500','06866000','06666650','05666500','05000500','06000600']),
 ('a blood knight',24,3,7,[],['00111000','01555100','01888100','00151000','52555250','12555210','00222000','00505000']),
 ('an ember drake',30,3,8,['bolt'],['02000200','02888200','00898000','20282020','22888220','00282000','02808200','02000200']),
]
for i,(name,hp,atk,depth,abilities,rows) in enumerate(designs):
 frames=[rows[:],rows[:],rows[:],rows[:]]
 # Breathing/wing motion: highlight pulses and a one-pixel lower-foot variation.
 frames[1]=[r.replace('8','9') for r in rows]
 frames[3]=[r.replace('8','2') for r in rows]
 frames[2]=rows[:6]+[rows[7],rows[6]]
 entries.append(dict(key='original-'+str(i),name=name,hp=hp,atk=atk,depth=depth,abilities=abilities,range=3 if 'bolt' in abilities else 1,sight=4,col=8,from_source='Original design / fantasy bestiary',frames=frames))
from full_cart_bestiary import expand
entries=expand(entries,H.parent.parent)
prior=json.loads((H/'editor/bestiary-v1-pack.js').read_text().split('const BESTIARY_V1_PACK = ')[1].rstrip(';\n'))
for e in entries:
 current=next((m for m in g['monsters'] if m.get('catalog_key')==e['key']),None)
 if current:
  previous=next((v for v in prior if v['key']==e['key']),None)
  if previous and g.get('bestiary_revision')!='additive-v2':
   for k in ['name','hp','atk','depth','abilities','range','sight','col','from_source']:
    if current.get(k)==previous.get(k):current[k]=e[k]
   for k,rows in enumerate(e['frames']):
    n=current['anim']+k-256
    if tile(g['sheet2'],n)==previous['frames'][k]:put(g['sheet2'],n,rows)
  continue
 used={m['code'] for m in g['monsters']}|{0,16,17}
 for m in g['monsters']:
  if m['anim']<256:used.update(range(m['anim'],m['anim']+(1 if m['prop'] else 4)))
 used.update(int(row[i:i+2],16) for f in g['floors'] for row in f['tiles'] for i in range(0,len(row),2))
 code=next(n for n in range(1,256) if n not in used and not g['flags'][n] and (not any(c!='0' for r in tile(g['sheet'],n) for c in r) or 128<=n<176))
 usedslots={m['anim']+k for m in g['monsters'] if m['anim']>=256 for k in range(4)}
 slot=next(n for n in range(256,381,4) if all(n+k not in usedslots and all(c=='0' for r in tile(g['sheet2'],n+k-256) for c in r) for k in range(4)))
 assert len(g['monsters'])<LD.MAXENT_IDS
 for k,rows in enumerate(e['frames']):put(g['sheet2'],slot+k-256,rows)
 g['monsters'].append(dict({k:e[k] for k in ['name','hp','atk','depth','abilities','range','sight','col']}, anim=slot,code=code,prop=False,itemchance=0,enabled=True,catalog_key=e['key'],from_source=e['from_source']))
g['monster_art_style']='original';g['monster_art_revision']='additive-v2';g['bestiary_revision']='additive-v2'
(H/'data/game.json').write_text(json.dumps(g,indent=1)+'\n')
(H/'editor/bestiary-pack.js').write_text('// Generated by tools/make_bestiary.py.\nconst BESTIARY_PACK = '+json.dumps(entries,separators=(',',':'))+';\n')
print('Bestiary:',len(g['monsters']),'entity types; complete BulbaRogue and Crocolike rosters.')
