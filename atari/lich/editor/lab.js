'use strict';
// Shares the existing editor's game, sprite, map and persistence helpers.
const lab = { depth: 1, seed: 1, zoom: 2, selected: new Set(), brush: 0, level: 1, weapon: -1,
  mode: 'group', trials: 200, encounter: [2], result: null, batch: null, frame: 0 };
function labField(label, input) { input.setAttribute('aria-label', label); return h('label', { class: 'lab-field' }, h('span', {}, label), input); }
function labNumber(key, min, max, after = () => render()) {
  return numInput(lab, key, { min, max, after });
}
function labSelect(key, options, after = () => render()) {
  const s = h('select', {}, ...options.map(([value, label]) => h('option', { value, selected: String(lab[key]) === String(value) }, label)));
  s.addEventListener('change', () => { lab[key] = typeof lab[key] === 'number' ? Number(s.value) : s.value; after(); });
  return s;
}
function labHero() {
  return h('div', { class: 'actions lab-controls' },
    labField('Hero level', labNumber('level', 1, 50)),
    labField('Weapon (normal, unenchanted)', labSelect('weapon', [[-1, 'Unarmed'], ...G.items.flatMap((it, i) => it.type === 1 ? [[i, `${it.name} (+${it.atk})`]] : [])])),
    h('span', { class: 'note' }, `${G.monsters[0].hp + (lab.level - 1) * G.params.lvl_hp} HP · ${labAttack()} damage / hit`));
}
function labAttack() { return G.monsters[0].atk + (lab.level - 1) * G.params.lvl_atk + (G.items[lab.weapon]?.atk || 0); }
function labConfig(seed = lab.seed) {
  return { level: lab.level, weaponAttack: G.items[lab.weapon]?.atk || 0, mode: lab.mode, seed };
}
function labCards(entries) {
  return h('div', { class: 'lab-cards' }, ...entries.map(([label, value]) => h('div', { class: 'panel lab-card' }, h('span', {}, label), h('strong', {}, value))));
}
function labOpenEncounter(ids) {
  lab.encounter = ids; lab.result = null; lab.batch = null; tab = 'encounters'; render();
}
VIEWS.levels = () => {
  lab.depth = Math.min(lab.depth, G.params.last_floor);
  const assigned = G.floor_plan[lab.depth - 1], custom = G.floors[assigned];
  let floor;
  try { floor = custom || (typeof LichPlay !== 'undefined' ? new LichPlay.Game(G, {depth:lab.depth, seed:lab.seed}).rawFloor : LichLab.sampleFloor(G, lab.depth, lab.seed)); }
  catch (error) { return h('div', {}, h('p', {class:'err'}, error.message), labField('Seed', labNumber('seed', 0, 4294967295)), h('p', {class:'note'}, 'Try another seed or adjust room sizes and budgets in Rules.')); }
  const roster = LichLab.roster(G, floor), grouped = new Map();
  roster.forEach(e => grouped.set(e.id, (grouped.get(e.id) || 0) + 1));
  const box = h('div');
  box.append(h('h2', {}, 'Level inspector'), h('p', { class: 'note' },
    'Inspect every enemy, select an encounter, or paint placements. Pink rings mark enemies; blue rings mark selected enemies. Coordinates start at 0.'),
    h('div', { class: 'actions lab-controls' },
      labField('Floor', labSelect('depth', Array.from({ length: G.params.last_floor }, (_, i) => [i + 1, i + 1]), () => { lab.selected.clear(); render(); })),
      !custom && labField('Layout seed', labNumber('seed', 0, 4294967295, () => { lab.selected.clear(); render(); })),
      !custom && h('button', { onclick: () => { lab.seed++; lab.selected.clear(); render(); } }, 'New seed'),
      labField('Zoom', labSelect('zoom', [[1, '1×'], [2, '2×'], [3, '3×']])),
      h('span', { class: 'tag' }, custom ? `Saved map: ${custom.name}` : 'Gameplay generator preview')));
  box.append(h('p', { class: 'note' }, custom
    ? 'This is the map assigned to this floor. Placement edits are saved to your editor session and included in game.json exports.'
    : 'Generated by the JavaScript gameplay port with room drift, doors, furniture, loot, traps and special rooms. Play this floor uses the same starting layout and seed. Browser RNG differs from Atari POKEY, so this is not a byte-identical Atari seed. Save it as a custom floor to export these placements.'));
  box.append(labCards([['Enemies', roster.length], ['Combined HP', roster.reduce((s, e) => s + G.monsters[e.id - 1].hp, 0)],
    ['Combined base attack', roster.reduce((s, e) => s + G.monsters[e.id - 1].atk, 0)], ['Enemy types', grouped.size]]));
  if (!custom) box.append(h('button', { class: 'primary', onclick: () => {
    G.floors.push(clone(floor)); G.floor_plan[lab.depth - 1] = G.floors.length - 1;
    curFloor = G.floors.length - 1; lab.selected.clear(); changed('Design saved and assigned to this floor. Export game.json to build it.'); render();
  } }, 'Save as custom floor'));
  else box.append(h('button', { onclick: () => { curFloor = assigned; tab = 'floors'; render(); } }, 'Open full map editor'));
  box.append(h('button', {onclick: () => { play.seed=lab.seed; play.depth=lab.depth; play.level=lab.level; tab='play'; history.replaceState(null,'','#play'); playStart(); }}, 'Play this floor'));
  const controls = h('div', { class: 'actions lab-controls' });
  const selectionText = h('span', { class: 'note' });
  const selectAll = () => { lab.selected = new Set(roster.map(e => e.y * 128 + e.x)); redraw(); };
  controls.append(labField('Map click', labSelect('brush', [[0, 'Select enemy'], [1, 'Erase to floor'], ...LichLab.enemies(G).map(m => [m.code, `Place ${m.name}`])])),
    h('button', { onclick: selectAll }, 'Select all enemies'),
    h('button', { onclick: () => { lab.selected.clear(); redraw(); } }, 'Clear selection'),
    h('button', { onclick: () => {
      const ids = roster.filter(e => lab.selected.has(e.y * 128 + e.x)).map(e => e.id);
      if (!ids.length) return status('Select at least one enemy on the map.', true);
      labOpenEncounter(ids);
    } }, 'Simulate selected'), selectionText);
  box.append(controls);
  let mapWidth = 16, mapHeight = 8;
  for (let y = 0; y < 32; y++) for (let x = 0; x < 128; x++) {
    if (floorGet(floor, x, y)) { mapWidth = Math.max(mapWidth, Math.min(128, x + 2)); mapHeight = Math.max(mapHeight, Math.min(32, y + 2)); }
  }
  const size = 8 * lab.zoom, canvas = h('canvas', { class: 'px', width: mapWidth * size, height: mapHeight * size, 'aria-label': 'Level map; enemy list below provides keyboard selection' });
  const detail = h('div', { class: 'panel lab-detail' }, 'Click an enemy to inspect it.');
  const redraw = () => {
    const ctx = canvas.getContext('2d'); drawFloor(ctx, floor, lab.zoom, { grid: lab.zoom > 1 });
    for (const e of roster) {
      ctx.strokeStyle = lab.selected.has(e.y * 128 + e.x) ? '#29adff' : '#ff77a8';
      ctx.lineWidth = lab.zoom; ctx.strokeRect(e.x * size + 1, e.y * size + 1, size - 2, size - 2);
    }
    selectionText.textContent = `${roster.filter(e => lab.selected.has(e.y * 128 + e.x)).length} selected`;
    box.querySelectorAll('[data-enemy-cell]').forEach(b => b.setAttribute('aria-pressed', String(lab.selected.has(Number(b.dataset.enemyCell)))));
  };
  const inspect = e => {
    const m = G.monsters[e.id - 1];
    detail.replaceChildren(animCanvas(() => entFrames(m), 4), h('strong', {}, `${m.name} · (${e.x}, ${e.y})`),
      h('span', {}, `HP ${m.hp} · ATK ${m.atk} · range ${m.range} · sight ${m.sight}`),
      h('span', { class: 'note' }, m.abilities.join(', ') || 'No special abilities'),
      h('button', { onclick: () => labOpenEncounter([e.id]) }, 'Simulate this enemy'));
  };
  const toggle = e => { const key = e.y * 128 + e.x; lab.selected.has(key) ? lab.selected.delete(key) : lab.selected.add(key); inspect(e); redraw(); };
  canvas.addEventListener('click', event => {
    const r = canvas.getBoundingClientRect();
    const x = Math.floor((event.clientX - r.left) * canvas.width / r.width / size), y = Math.floor((event.clientY - r.top) * canvas.height / r.height / size);
    if (x < 0 || y < 0 || x > 127 || y > 31) return;
    if (lab.brush) {
      if (!custom) return status('Save this design as a custom floor before editing placements.', true);
      const old = floorGet(custom, x, y);
      if (old === G.params.tile_start || old === G.params.tile_exit) return status('Use the full map editor to change the start or stairs.', true);
      floorSet(custom, x, y, lab.brush); lab.selected.clear(); changed('Placement saved.'); render();
    } else { const e = roster.find(e => e.x === x && e.y === y); if (e) toggle(e); }
  });
  box.append(h('div', { class: 'mapwrap lab-map' }, canvas), detail, h('h2', {}, 'Enemy roster'));
  const table = h('table', { class: 'lab-table' }, h('tr', {}, ...['Enemy', 'Count', 'HP / each', 'ATK / each', 'Abilities', 'Positions'].map(t => h('th', {}, t))));
  for (const [id, count] of grouped) {
    const m = G.monsters[id - 1];
    table.append(h('tr', {}, h('td', {}, animCanvas(() => entFrames(m), 3), ' ', m.name), h('td', {}, count),
      h('td', {}, numInput(m, 'hp', { min: 1, max: 127, after: render })), h('td', {}, numInput(m, 'atk', { min: 0, max: 99, after: render })),
      h('td', {}, m.abilities.join(', ') || '—'), h('td', {}, ...roster.filter(e => e.id === id).map(e =>
        h('button', { class: 'small', 'data-enemy-cell': e.y * 128 + e.x, onclick: () => toggle(e) }, `${e.x},${e.y}`)))));
  }
  box.append(h('p', { class: 'note' }, 'HP and attack edits change the enemy type everywhere in the game.'), h('div', { class: 'scroll' }, table));
  redraw(); return box;
};
VIEWS.balance = () => {
  const box = h('div', {}, h('h2', {}, 'Game balance'), labHero(),
    h('p', { class: 'note' }, 'Baseline comparisons use fixed damage, full hero HP, hero attacking first, and no special abilities. They exclude movement, consumables and level-ups. Use encounters for supported status effects and XP.'));
  const chart = h('div', { class: 'panel' });
  const table = h('table', { class: 'lab-table' }, h('tr', {}, ...['Floor', 'Budget', 'Eligible enemy types', 'Mean HP', 'Mean base ATK'].map(t => h('th', {}, t))));
  const maxBudget = Math.max(1, ...G.budget.slice(0, G.params.last_floor));
  for (let d = 1; d <= G.params.last_floor; d++) {
    const pool = LichLab.eligible(G, d), mean = key => pool.length ? (pool.reduce((s, m) => s + m[key], 0) / pool.length).toFixed(1) : '—';
    table.append(h('tr', {}, h('td', {}, d), h('td', {}, numInput(G.budget, d - 1, { min: 0, max: 200, after: render })),
      h('td', {}, pool.map(m => m.name).join(', ') || 'None — no random enemies'), h('td', {}, mean('hp')), h('td', {}, mean('atk'))));
    chart.append(h('div', { class: 'lab-bar-row' }, h('span', {}, `Floor ${d}`), h('div', { class: 'lab-bar-track' }, h('div', { class: 'lab-bar', style: `width:${G.budget[d - 1] / maxBudget * 100}%` })), h('b', {}, G.budget[d - 1])));
  }
  box.append(h('h2', {}, 'Enemy budget by floor'), chart, h('p', { class: 'note' }, 'The game fills through budget inclusively (usually budget + 1 random enemies), then adds mimics. Room placement can already exceed the budget. Bosses and pot spawns are additional.'), h('div', { class: 'scroll' }, table));
  const t = h('table', { class: 'lab-table' }, h('tr', {}, ...['Enemy', 'HP', 'ATK', 'From floor', 'Hits to defeat', 'Baseline HP loss', 'Special abilities', ''].map(v => h('th', {}, v))));
  const attack = labAttack(), heroHp = G.monsters[0].hp + (lab.level - 1) * G.params.lvl_hp;
  for (const m of LichLab.enemies(G)) {
    const live = G.monsters[m.id - 1], hits = attack > 0 ? Math.ceil(m.hp / attack) : Infinity, loss = Number.isFinite(hits) ? Math.max(0, hits - 1) * m.atk : Infinity;
    t.append(h('tr', {}, h('td', {}, animCanvas(() => entFrames(live), 3), ' ', m.name),
      ...['hp', 'atk', 'depth'].map(key => h('td', {}, numInput(live, key, { min: key === 'hp' ? 1 : 0, max: key === 'hp' ? 127 : 99, after: render }))),
      h('td', {}, Number.isFinite(hits) ? hits : 'Cannot defeat'), h('td', { class: loss >= heroHp ? 'err' : '' }, Number.isFinite(loss) ? `${loss} / ${heroHp}` : '—'),
      h('td', {}, m.abilities.join(', ') || '—'), h('td', {}, h('button', { onclick: () => labOpenEncounter([m.id]) }, 'Simulate'))));
  }
  box.append(h('h2', {}, 'Enemy comparisons'), h('div', { class: 'scroll' }, t)); return box;
};
VIEWS.encounters = () => {
  lab.encounter = lab.encounter.filter(id => G.monsters[id - 1] && !G.monsters[id - 1].prop && id !== 1);
  const box = h('div', {}, h('h2', {}, 'Encounter simulator'),
    h('p', { class: 'note' }, 'Adjacent-combat estimate, not an emulator. The hero attacks the first surviving enemy. Group mode lets all survivors retaliate; sequence mode fights them one at a time. Starts at full HP and the selected level’s XP threshold. Poison, paralysis, stun, slow, vampire, weapon theft, boss melee healing and XP level-ups are modeled. Status timing is approximated. No movement, range, terrain, consumables, enchanted weapons or post-combat poison ticks. Curse and item theft consume the first hit but have no further effect here.'), labHero());
  box.append(h('div', { class: 'actions lab-controls' }, labField('Mode', labSelect('mode', [['group', 'Group: all enemies attack'], ['sequence', 'Sequence: one at a time']])),
    labField('Seed', labNumber('seed', 0, 4294967295)), labField('Trials', labNumber('trials', 1, 1000))));
  const choose = h('select', { 'aria-label': 'Enemy to add' }, ...LichLab.enemies(G).map(m => h('option', { value: m.id }, m.name)));
  box.append(h('div', { class: 'actions' }, choose, h('button', { onclick: () => { if (lab.encounter.length < 200) lab.encounter.push(Number(choose.value)); lab.result = null; lab.batch = null; render(); } }, 'Add enemy'),
    h('button', { onclick: () => { lab.encounter = []; lab.result = null; lab.batch = null; render(); } }, 'Clear encounter')));
  const counts = new Map(); lab.encounter.forEach(id => counts.set(id, (counts.get(id) || 0) + 1));
  box.append(h('div', { class: 'lab-roster' }, ...[...counts].map(([id, n]) => {
    const m = G.monsters[id - 1]; return h('div', { class: 'panel' }, animCanvas(() => entFrames(m), 3), ` ${m.name} × ${n} `,
      h('button', { class: 'small', 'aria-label': `Remove one ${m.name}`, onclick: () => { lab.encounter.splice(lab.encounter.lastIndexOf(id), 1); lab.result = null; lab.batch = null; render(); } }, '−'));
  })));
  const signature = JSON.stringify([G.monsters, G.params, G.items[lab.weapon], G.xp_req, lab.encounter, labConfig(), lab.trials]);
  if (lab.resultKey !== signature) { lab.result = null; lab.batch = null; }
  const run = batch => {
    if (!lab.encounter.length) return status('Add at least one enemy.', true);
    lab.result = LichLab.simulate(G, lab.encounter, labConfig()); lab.frame = 0; lab.resultKey = signature; lab.batch = null;
    if (batch) {
      let wins = 0, limits = 0, hp = 0, turns = 0;
      for (let i = 0; i < lab.trials; i++) {
        const r = LichLab.simulate(G, lab.encounter, { ...labConfig((lab.seed + i) >>> 0), log: false });
        wins += r.outcome === 'victory'; limits += r.outcome === 'turn limit'; hp += r.hp; turns += r.turn;
      }
      lab.batch = { wins, limits, hp: hp / lab.trials, turns: turns / lab.trials };
    }
    render();
  };
  box.append(h('div', { class: 'actions lab-controls' }, h('button', { class: 'primary', onclick: () => run(false) }, 'Run encounter'), h('button', { onclick: () => run(true) }, 'Run multiple seeds')));
  const warnings = [...new Set(lab.encounter.flatMap(id => G.monsters[id - 1].abilities).filter(a => ['bolt', 'blink', 'flee', 'summon', 'hunter', 'blind', 'invisible', 'pounce'].includes(a)))];
  if (warnings.length) box.append(h('p', { class: 'lab-warning' }, `Not simulated in this encounter: ${warnings.join(', ')}. Results can differ substantially from gameplay.`));
  if (!lab.result) { box.append(h('p', { class: 'note' }, 'Run to see the turn replay, combat log and outcome. Changing inputs invalidates previous results.')); return box; }
  const r = lab.result;
  box.append(labCards([['Outcome', r.outcome], ['HP remaining', `${r.hp} / ${r.maxHp}`], ['Turns', r.turn], ['Kills / final level', `${r.kills} / ${r.level}`]]));
  if (lab.batch) box.append(labCards([['Win rate', `${(100 * lab.batch.wins / lab.trials).toFixed(1)}%`], ['Mean remaining HP', lab.batch.hp.toFixed(1)], ['Mean turns', lab.batch.turns.toFixed(1)], ['Turn limits', lab.batch.limits]]), h('p', { class: 'note' }, `${lab.trials} consecutive seeds starting at ${lab.seed}. Repeated seeds only vary stochastic abilities; ordinary melee is deterministic.`));
  const arena = h('div', { class: 'lab-arena panel' }), replayLabel = h('span');
  const slider = h('input', { type: 'range', min: 0, max: r.snapshots.length - 1, value: lab.frame, 'aria-label': 'Replay turn', style: 'width:min(500px,65vw)' });
  const paint = () => {
    const frame = r.snapshots[lab.frame]; replayLabel.textContent = `Turn ${frame.turn}`;
    arena.replaceChildren(h('div', { class: 'lab-fighter' }, spriteCanvas(G.monsters[0].anim, 5), h('b', {}, 'Hero'), h('meter', { min: 0, max: frame.maxHp, value: frame.hp }), `${frame.hp} HP`),
      ...lab.encounter.map((id, i) => { const m = G.monsters[id - 1]; return h('div', { class: `lab-fighter ${frame.enemies[i] ? '' : 'lab-dead'}` }, spriteCanvas(m.anim, 4), h('span', {}, m.name), h('meter', { min: 0, max: m.hp, value: frame.enemies[i] }), `${frame.enemies[i]} HP`); }));
  };
  slider.addEventListener('input', () => { lab.frame = Number(slider.value); paint(); });
  box.append(h('h2', {}, 'Turn replay'), h('div', { class: 'actions' }, slider, replayLabel), arena);
  const log = h('div', { class: 'lab-log panel', tabindex: 0 });
  r.log.forEach(e => log.append(h('div', {}, h('span', { class: 'note' }, `Turn ${e.turn} · `), e.message)));
  box.append(h('h2', {}, 'Combat log'), log); paint(); return box;
};
