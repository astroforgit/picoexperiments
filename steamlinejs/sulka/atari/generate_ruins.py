#!/usr/bin/env python3
"""Pack surreal sketch ruins into 16-tone VBXE backgrounds, enlarged 2x in VRAM."""
from pathlib import Path
from PIL import Image, ImageOps
ROOT = Path(__file__).resolve().parent.parent
WIDTH, HEIGHT = 112, 70
COLOURS = [(i * 6, i * 6, i * 6) for i in range(16)]


def main():
    lines = ['; Generated by generate_ruins.py: packed high/low 4-bit pixels.']
    for number, address in ((1, 0x1000), (2, 0xB000)):
        source = Image.open(ROOT / f'assets/ukr{number}-line-background-source.png').convert('RGB')
        source = ImageOps.fit(source, (WIDTH, HEIGHT), Image.Resampling.LANCZOS)
        grey = ImageOps.autocontrast(source.convert('L'), cutoff=1)
        pixels = []
        for y in range(HEIGHT):
            for x in range(WIDTH):
                # Fade into the original board colour at the frame edges.
                fade = min(1, x / 5, (WIDTH-1-x) / 5, y / 4, (HEIGHT-1-y) / 4)
                value = grey.getpixel((x, y))
                pixels.append(0 if value < 12 else round((value / 255) ** .9 * 15 * fade))
        packed = bytes((pixels[i] << 4) | pixels[i+1] for i in range(0, len(pixels), 2))
        assert len(packed) == 3920
        lines.extend([f'        org ${address:04X}', f'ruins_{number}_packed'])
        for i in range(0, len(packed), 24):
            lines.append('        dta ' + ','.join(f'${b:02X}' for b in packed[i:i+24]))
        lines.append(f'        ert * > ${address+0x1000:04X}')
        preview = Image.new('RGB', (WIDTH, HEIGHT))
        preview.putdata([COLOURS[p] for p in pixels])
        preview.resize((224,140), Image.Resampling.NEAREST).save(ROOT / f'assets/ukr{number}-line-background-vbxe.png')
    (ROOT/'atari/generated/sojka-ruins.inc').write_text('\n'.join(lines)+'\n')
    (ROOT/'atari/generated/sojka-ruins-palette.inc').write_text('\n'.join(
        '        dta '+','.join(map(str,(32+i,*rgb))) for i,rgb in enumerate(COLOURS))+'\n')
    print('Generated two surreal sketch backgrounds: 224x140 display, 16 tones, 3920 bytes each.')

if __name__ == '__main__':
    main()
