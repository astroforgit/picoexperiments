#!/usr/bin/env python3
"""Generate runtime tables and VRAM payloads.

gen/tables.asm  NES palette as VBXE RGB, pixel expansion tables xt0-xt3
gen/chr_index.bin  32 CHR banks x 256 tiles -> unique tile number (16-bit LE)
gen/chr_raw.bin    unique tiles, 16 bytes each: per row the two expansion
                   indices (hi4 of plane1)<<4|hi4 of plane0, then the low halves
"""
from pathlib import Path
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / 'gen'
SRC = ROOT.parent / 'double-dragon-snes-main/double-dragon-snes-main/src'


def asm_bytes(name):
    out = bytearray()
    for line in (SRC / name).read_text().splitlines():
        line = line.split(';', 1)[0].strip()
        if line.lower().startswith('.byte'):
            out += bytes(int(v.strip()[1:], 16) for v in line[5:].split(',') if v.strip())
    return out


def palette():
    vals = asm_bytes('palette_lookup.asm')
    rgb = []
    for i in range(64):
        w = vals[i * 2] | vals[i * 2 + 1] << 8
        rgb.append(tuple(((w >> s) & 31) * 255 // 31 for s in (0, 5, 10)))
    return rgb


def expansion_tables():
    t = [[0] * 256 for _ in range(4)]
    for idx in range(256):
        p0, p1 = idx & 15, idx >> 4
        for j in range(4):
            c = ((p0 >> (3 - j)) & 1) | (((p1 >> (3 - j)) & 1) << 1)
            t[j][idx] = 0 if c == 0 else 0xFC | c
    return t


def chr_tiles():
    """32 banks x 256 tiles of (p0, p1) row pairs, NES 2bpp."""
    banks = []
    for f in range(8):
        data = asm_bytes(f'chrom-tiles-{f}.asm')
        assert len(data) == 32768, f
        for b in range(4):
            tiles = []
            for t in range(256):
                i = (b * 256 + t) * 32
                tiles.append([(data[i + y * 2], data[i + y * 2 + 1]) for y in range(8)])
            banks.append(tiles)
    return banks


def raw16(rows):
    out = bytearray()
    for p0, p1 in rows:
        out.append((p1 & 0xF0) | (p0 >> 4))
        out.append(((p1 & 0x0F) << 4) | (p0 & 0x0F))
    return bytes(out)


def main():
    GEN.mkdir(exist_ok=True)
    rgb = palette()
    xt = expansion_tables()
    lines = ['; generated by tools/make_data.py']
    for name, k in (('nes_r', 0), ('nes_g', 1), ('nes_b', 2)):
        lines.append(f'{name}')
        for i in range(0, 64, 16):
            lines.append('        dta ' + ','.join(f'${rgb[j][k]:02x}' for j in range(i, i + 16)))
    lines.append('        .align $100')
    for j in range(4):
        lines.append(f'xt{j}')
        for i in range(0, 256, 16):
            lines.append('        dta ' + ','.join(f'${v:02x}' for v in xt[j][i:i + 16]))
    (GEN / 'tables.asm').write_text('\n'.join(lines) + '\n')

    banks = chr_tiles()
    uniq = {}
    raw = bytearray()
    index = bytearray()
    for b in range(32):
        for t in range(256):
            r = raw16(banks[b][t])
            if r not in uniq:
                uniq[r] = len(uniq)
                raw += r
            index += uniq[r].to_bytes(2, 'little')
    (GEN / 'chr_index.bin').write_bytes(index)
    (GEN / 'chr_raw.bin').write_bytes(raw)
    print(f'CHR: {len(uniq)} unique tiles, {len(raw)} bytes raw, index {len(index)}')
    assert len(raw) <= 0x7C000 - 0x64000, 'raw CHR does not fit before the sprite slot'


if __name__ == '__main__':
    main()
