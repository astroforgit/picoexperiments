#!/usr/bin/env node
'use strict';

// Compiles bimbaj.json (levels and story texts in campaign order) into
// bimbaj-data.inc (tables in main RAM) and bimbaj-bank.inc (level and page
// bytes, staged at $8000 and copied under the OS ROM by INIT segments).
const fs = require('fs');
const path = require('path');
const format = require('./bimbaj-format');

const root = __dirname;
const project = JSON.parse(fs.readFileSync(path.join(root, 'bimbaj.json'), 'utf8'));
const result = format.compile(project);
if (result.errors.length) {
    for (const error of result.errors) console.error(error.message);
    process.exit(1);
}

const hex = value => '$' + value.toString(16).toUpperCase().padStart(2, '0');
const word = value => '$' + value.toString(16).toUpperCase().padStart(4, '0');
const bytesLines = bytes => {
    const out = [];
    for (let i = 0; i < bytes.length; i += 16) out.push('        dta ' + bytes.slice(i, i + 16).map(hex).join(','));
    return out;
};
// MADS needs at least one value after dta.
const table = (label, values) => `${label} dta ${(values.length ? values : [0]).join(',')}`;
const screenString = (label, text) =>
    [`${label} dta ${label}_end-${label}-1,d'${text}'`, `${label}_end`];

const pages = result.breaks.flatMap(pause => pause.pages);
const levelAddresses = result.bank.addresses.slice(0, result.levels.length);
const pageAddresses = result.bank.addresses.slice(result.levels.length);
const firstPages = [];
result.breaks.reduce((first, pause) => (firstPages.push(first), first + pause.pages.length), 0);

const total = result.levels.length;
const data = [
    '; Generated by generate_data.js from bimbaj.json. Do not edit.',
    `LEVEL_COUNT = ${total}`,
    `STORY_BREAK_TOTAL = ${result.breaks.length}`,
    `STORY_PAGE_COUNT = ${pages.length}`,
    '',
    ...result.levels.map((level, index) => `; level ${index + 1} at ${word(levelAddresses[index])}: ${level.name}`),
    table('level_ptr_lo', levelAddresses.map(address => `<${word(address)}`)),
    table('level_ptr_hi', levelAddresses.map(address => `>${word(address)}`)),
    '',
    '; A story break is shown once this many levels are complete.',
    table('story_break_level', result.breaks.map(pause => pause.after)),
    table('story_break_first', firstPages),
    table('story_break_pages', result.breaks.map(pause => pause.pages.length)),
    table('story_page_lo', pageAddresses.map(address => `<${word(address)}`)),
    table('story_page_hi', pageAddresses.map(address => `>${word(address)}`)),
    '',
    ...screenString('s_of_total', `/${String(total).padStart(2, '0')} `),
    ...screenString('s_all_done', `ALL ${total} LEVELS COMPLETE! FIRE TO REPLAY.`),
    '',
];
fs.writeFileSync(path.join(root, 'bimbaj-data.inc'), data.join('\n'));

// Each bank window becomes one or more staged chunks: a(destination),
// a(length), bytes. bank_loader copies a chunk when its INIT segment runs.
const blobs = [...result.levels.map(level => level.bytes), ...pages.map(page => page.bytes)];
const bank = ['; Generated by generate_data.js from bimbaj.json. Do not edit.'];
for (const window of result.bank.windows) {
    const bytes = new Array(window.next - window.start).fill(0);
    blobs.forEach((blob, index) => {
        const offset = result.bank.addresses[index] - window.start;
        if (offset >= 0 && offset < bytes.length) bytes.splice(offset, blob.length, ...blob);
    });
    for (let offset = 0; offset < bytes.length; offset += format.STAGE_LIMIT) {
        const chunk = bytes.slice(offset, offset + format.STAGE_LIMIT);
        bank.push('', '        org bank_stage', `        dta a(${word(window.start + offset)}),a(${chunk.length})`);
        bank.push(...bytesLines(chunk), '        ini bank_loader');
    }
}
fs.writeFileSync(path.join(root, 'bimbaj-bank.inc'), bank.join('\n') + '\n');

console.log(`Wrote ${total} levels, ${result.breaks.length} story break(s), ${pages.length} page(s); ` +
    `${result.used} of ${result.capacity} bank bytes used.`);
